-- Legacy routers did not store the function binding required by current authorization.
SET @PEACH_ROUTER_DDL = (SELECT IF(NOT EXISTS (
 SELECT 1 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='PEACH_ROUTER' AND COLUMN_NAME='FUNC_CODE'
), 'ALTER TABLE PEACH_ROUTER ADD COLUMN FUNC_CODE VARCHAR(128) NULL COMMENT ''关联功能编码''', 'SELECT 1'));
PREPARE PEACH_ROUTER_STATEMENT FROM @PEACH_ROUTER_DDL;
EXECUTE PEACH_ROUTER_STATEMENT;
DEALLOCATE PREPARE PEACH_ROUTER_STATEMENT;
UPDATE PEACH_ROUTER r JOIN PEACH_FUNCTION f ON f.TENANT_ID=r.TENANT_ID AND f.APP_ID=r.APP_ID AND f.FUNC_URL=r.ROUTER_URL AND f.IS_DELETE=0
SET r.FUNC_CODE=f.FUNC_CODE WHERE r.FUNC_CODE IS NULL OR r.FUNC_CODE='';
