-- Upgrade existing consumer records to the current JDBC lease/fencing contract.
-- Select the target Peach database first. Compatible with MySQL 5.7; repeatable.
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SET @PEACH_CONSUME_DDL = (
    SELECT IF(COUNT(*) = 0, 'ALTER TABLE MQ_CONSUME_RECORD ADD COLUMN OWNER_TOKEN VARCHAR(64) NULL COMMENT ''当前认领者令牌''',
        'SELECT ''OWNER_TOKEN already exists'' AS MIGRATION_STATUS')
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'MQ_CONSUME_RECORD' AND COLUMN_NAME = 'OWNER_TOKEN'
);
PREPARE PEACH_CONSUME_STATEMENT FROM @PEACH_CONSUME_DDL;
EXECUTE PEACH_CONSUME_STATEMENT;
DEALLOCATE PREPARE PEACH_CONSUME_STATEMENT;

