CREATE TABLE PEACH_ROLE
(
    ID             VARCHAR(32) NOT NULL COMMENT '物理主键',
    ROLE_ID          VARCHAR(32)  NOT NULL COMMENT '角色ID',
    TENANT_ID        VARCHAR(32)  NOT NULL COMMENT '租户ID',
    ORG_ID           VARCHAR(32)  NOT NULL COMMENT '机构ID',
    ROLE_CODE        VARCHAR(20)  NOT NULL COMMENT '角色编码',
    FISCAL           SMALLINT(4)  NOT NULL COMMENT '年度',
    ROLE_NAME        VARCHAR(64)  NULL COMMENT '角色名称',
    ROLE_DESC        VARCHAR(64)  NULL COMMENT '角色描述',
    ROLE_SCOPE       VARCHAR(20)  NULL COMMENT '角色范围',
    ROLE_TYPE        VARCHAR(20)  NULL COMMENT '角色类型',
    TENANT_REF_ID    VARCHAR(32)  NULL COMMENT 'SaaS租户物理ID，新授权记录必填',
    APP_REF_ID       VARCHAR(32)  NULL COMMENT 'SaaS应用物理ID，新授权记录必填',
    AUTH_YEAR        SMALLINT     NULL COMMENT '自然年度授权范围',
    ROLE_STATUS      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED',
    VERSION          BIGINT       NOT NULL DEFAULT 0 COMMENT '角色并发版本',
    CREATED_TIME     VARCHAR(20)  NULL COMMENT '创建时间',
    CREATOR_ID       VARCHAR(32)  NULL COMMENT '创建人ID',
    MODIFY_TIME      VARCHAR(20)  NULL COMMENT '修改时间',
    MODIFIER_ID      VARCHAR(32)  NULL COMMENT '修改人ID',
    IS_DELETE        TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否删除',
    DELETED_AT       DATETIME(3) NULL COMMENT '逻辑删除时间',
    ACTIVE_SLOT     TINYINT GENERATED ALWAYS AS (CASE WHEN IS_DELETE = 0 THEN 1 ELSE NULL END) STORED,
    SKIP_URL         VARCHAR(64)  NULL COMMENT '角色登陆跳转',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_ROLE_ID_BIZ (ROLE_ID),
    UNIQUE KEY UK_ROLE_SAAS_CONTEXT (TENANT_REF_ID, APP_REF_ID, AUTH_YEAR, ROLE_CODE, ACTIVE_SLOT),
    CONSTRAINT CK_ROLE_AUTH_YEAR CHECK (AUTH_YEAR IS NULL OR AUTH_YEAR BETWEEN 1 AND 9999),
    CONSTRAINT CK_ROLE_STATE CHECK (ROLE_STATUS IN ('ACTIVE', 'DISABLED'))
) COMMENT='角色表';

CREATE UNIQUE INDEX UK_ROLE_CODE
    ON PEACH_ROLE (TENANT_ID, ORG_ID, ROLE_CODE, FISCAL, ACTIVE_SLOT);

CREATE INDEX IDX_ROLE_TENANT_ORG
    ON PEACH_ROLE (TENANT_ID, ORG_ID);
