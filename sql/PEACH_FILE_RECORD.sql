CREATE TABLE `PEACH_FILE_RECORD` (
  `FILE_ID` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '业务文件ID',
  `OBJECT_ID` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '物理对象ID',
  `BIZ_TYPE` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '业务类型',
  `BIZ_ID` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '业务ID',
  `BIZ_TAG` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '业务标签',
  `FILE_NAME` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '文件名',
  `DISPLAY_NAME` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '显示文件名',
  `CONTENT_TYPE` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '内容类型',
  `FILE_SIZE` bigint(20) DEFAULT NULL COMMENT '文件大小',
  `FILE_EXT` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '扩展名',
  `FILE_STATUS` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '文件状态',
  `DELETE_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '逻辑删除时间',
  `EXPIRE_DELETE_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '过期删除时间',
  `REMARK` varchar(500) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '备注',
  `TENANT_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '租户ID',
  `ORG_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '机构ID',
  `IS_DELETE` tinyint(1) DEFAULT '0' COMMENT '逻辑删除标记',
  `CREATED_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建时间',
  `CREATOR_ID` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建人ID',
  `MODIFY_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改时间',
  `MODIFIER_ID` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改人ID',
  PRIMARY KEY (`FILE_ID`),
  KEY `IDX_FILE_RECORD_CONTEXT_BIZ` (`TENANT_ID`,`ORG_ID`,`BIZ_TYPE`,`BIZ_ID`),
  KEY `IDX_FILE_RECORD_CONTEXT_OBJECT` (`TENANT_ID`,`ORG_ID`,`OBJECT_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='业务文件记录表';
