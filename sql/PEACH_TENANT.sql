CREATE TABLE PEACH_TENANT
(
    ID VARCHAR(36) NOT NULL,
    TENANT_ID VARCHAR(32) NOT NULL,
    TENANT_CODE VARCHAR(128) NOT NULL,
    TENANT_NAME VARCHAR(128) NOT NULL,
    TENANT_TYPE VARCHAR(32) NOT NULL DEFAULT 'ENTERPRISE',
    STATUS VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    DESCRIPTION VARCHAR(500) DEFAULT NULL,
    CONTACT_NAME VARCHAR(64) DEFAULT NULL,
    CONTACT_PHONE VARCHAR(32) DEFAULT NULL,
    CONTACT_EMAIL VARCHAR(128) DEFAULT NULL,
    ACTIVATED_TIME VARCHAR(32) DEFAULT NULL,
    CLOSED_AT VARCHAR(32) DEFAULT NULL,
    VERSION BIGINT NOT NULL DEFAULT 0,
    DELETED TINYINT NOT NULL DEFAULT 0,
    CREATOR_ID VARCHAR(36) DEFAULT NULL,
    CREATOR_CODE VARCHAR(36) DEFAULT NULL,
    CREATE_TIME VARCHAR(32) NOT NULL,
    MODIFIER_ID VARCHAR(32) DEFAULT NULL,
    MODIFIER_CODE VARCHAR(32) DEFAULT NULL COMMENT '修改人账号',
    MODIFY_TIME VARCHAR(32) DEFAULT NULL,
    DELETER VARCHAR(36) DEFAULT NULL,
    DELETE_TIME VARCHAR(32) DEFAULT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_TENANT_ID (TENANT_ID),
    UNIQUE KEY UK_TENANT_CODE (TENANT_CODE),
    KEY IDX_TENANT_NAME (TENANT_NAME),
    KEY IDX_TENANT_STATUS (STATUS, DELETED),
    KEY IDX_TENANT_CREATE_TIME (CREATE_TIME)
) COMMENT='租户主表';
