CREATE TABLE `PEACH_SCHEDULER_JOB` (
  `ID` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '任务主键',
  `JOB_CODE` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '稳定任务编码，全局唯一',
  `JOB_NAME` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '任务名称',
  `APPLICATION_NAME` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '目标业务应用名称',
  `HANDLER_NAME` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '目标 Handler 名称',
  `DESCRIPTION` varchar(512) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '任务说明',
  `SCHEDULE_TYPE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '调度类型：CRON、FIXED_RATE、ONCE',
  `CRON_EXPRESSION` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Quartz Cron 表达式',
  `INTERVAL_SECONDS` bigint(20) DEFAULT NULL COMMENT '固定周期秒数',
  `START_AT` datetime(3) DEFAULT NULL COMMENT '调度起始时间',
  `TIME_ZONE` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'Asia/Shanghai' COMMENT '调度时区',
  `MISFIRE_POLICY` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '错过触发策略',
  `CONCURRENCY_POLICY` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '并发策略：ALLOW、SKIP_IF_RUNNING、DISALLOW',
  `TIMEOUT_MS` bigint(20) NOT NULL COMMENT '单次执行超时毫秒数',
  `MAX_ATTEMPTS` int(11) NOT NULL DEFAULT '1' COMMENT '最大执行次数，含首次',
  `RETRY_INTERVAL_SECONDS` int(11) NOT NULL DEFAULT '60' COMMENT '重试间隔秒数',
  `PARAMETERS_JSON` longtext COLLATE utf8mb4_unicode_ci COMMENT '任务参数 JSON，禁止写入凭据字段',
  `STATE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '任务生命周期状态',
  `SCHEDULE_VERSION` bigint(20) NOT NULL DEFAULT '1' COMMENT '调度定义版本号',
  `SYNC_STATUS` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'Provider 同步状态：PENDING、SYNCED、FAILED',
  `LAST_SYNC_ERROR` varchar(1000) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '最近一次同步失败摘要',
  `NEXT_FIRE_TIME` datetime(3) DEFAULT NULL COMMENT '下次计划触发时间',
  `LAST_FIRE_TIME` datetime(3) DEFAULT NULL COMMENT '最近一次计划触发时间',
  `VERSION` bigint(20) NOT NULL DEFAULT '0' COMMENT '乐观锁版本号',
  `CREATOR_ID` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建人 ID',
  `CREATED_TIME` datetime(3) NOT NULL COMMENT '创建时间',
  `MODIFIER_ID` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改人 ID',
  `MODIFY_TIME` datetime(3) NOT NULL COMMENT '修改时间',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_SCHEDULER_JOB_CODE` (`JOB_CODE`),
  KEY `IDX_SCHEDULER_JOB_APP_HANDLER` (`APPLICATION_NAME`,`HANDLER_NAME`),
  KEY `IDX_SCHEDULER_JOB_STATE` (`STATE`),
  KEY `IDX_SCHEDULER_JOB_SYNC` (`SYNC_STATUS`,`MODIFY_TIME`),
  KEY `IDX_SCHEDULER_JOB_MODIFY_TIME` (`MODIFY_TIME`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='调度任务定义表';
