CREATE TABLE PEACH_SCHEDULER_JOB
(
    ID                     BIGINT       NOT NULL AUTO_INCREMENT COMMENT '任务主键',
    JOB_CODE               VARCHAR(128) NOT NULL COMMENT '稳定任务编码，全局唯一',
    JOB_NAME               VARCHAR(128) NOT NULL COMMENT '任务名称',
    APPLICATION_NAME       VARCHAR(128) NOT NULL COMMENT '目标业务应用名称',
    HANDLER_NAME           VARCHAR(128) NOT NULL COMMENT '目标 Handler 名称',
    DESCRIPTION            VARCHAR(512) NULL COMMENT '任务说明',
    SCHEDULE_TYPE          VARCHAR(32)  NOT NULL COMMENT '调度类型：CRON、FIXED_RATE、ONCE',
    CRON_EXPRESSION        VARCHAR(128) NULL COMMENT 'Quartz Cron 表达式',
    INTERVAL_SECONDS       BIGINT       NULL COMMENT '固定周期秒数',
    START_AT               DATETIME(3)  NULL COMMENT '调度起始时间',
    TIME_ZONE              VARCHAR(64)  NOT NULL DEFAULT 'Asia/Shanghai' COMMENT '调度时区',
    MISFIRE_POLICY         VARCHAR(32)  NOT NULL COMMENT '错过触发策略',
    CONCURRENCY_POLICY     VARCHAR(32)  NOT NULL COMMENT '并发策略：ALLOW、SKIP_IF_RUNNING、DISALLOW',
    TIMEOUT_MS             BIGINT       NOT NULL COMMENT '单次执行超时毫秒数',
    MAX_ATTEMPTS           INT          NOT NULL DEFAULT 1 COMMENT '最大执行次数，含首次',
    RETRY_INTERVAL_SECONDS INT          NOT NULL DEFAULT 60 COMMENT '重试间隔秒数',
    PARAMETERS_JSON        LONGTEXT     NULL COMMENT '任务参数 JSON，禁止写入凭据字段',
    STATE                  VARCHAR(32)  NOT NULL COMMENT '任务生命周期状态',
    SCHEDULE_VERSION       BIGINT       NOT NULL DEFAULT 1 COMMENT '调度定义版本号',
    SYNC_STATUS            VARCHAR(32)  NOT NULL COMMENT 'Provider 同步状态：PENDING、SYNCED、FAILED',
    LAST_SYNC_ERROR        VARCHAR(1000) NULL COMMENT '最近一次同步失败摘要',
    NEXT_FIRE_TIME         DATETIME(3)  NULL COMMENT '下次计划触发时间',
    LAST_FIRE_TIME         DATETIME(3)  NULL COMMENT '最近一次计划触发时间',
    VERSION                BIGINT       NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
    CREATOR_ID             VARCHAR(64)  NULL COMMENT '创建人 ID',
    CREATED_TIME           DATETIME(3)  NOT NULL COMMENT '创建时间',
    MODIFIER_ID            VARCHAR(64)  NULL COMMENT '修改人 ID',
    MODIFY_TIME            DATETIME(3)  NOT NULL COMMENT '修改时间',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_SCHEDULER_JOB_CODE (JOB_CODE),
    KEY IDX_SCHEDULER_JOB_APP_HANDLER (APPLICATION_NAME, HANDLER_NAME),
    KEY IDX_SCHEDULER_JOB_STATE (STATE),
    KEY IDX_SCHEDULER_JOB_SYNC (SYNC_STATUS, MODIFY_TIME),
    KEY IDX_SCHEDULER_JOB_MODIFY_TIME (MODIFY_TIME)
) COMMENT='调度任务定义表';
