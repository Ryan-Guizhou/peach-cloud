CREATE TABLE `PEACH_LOGIN_LOG` (
  `LOG_ID` varchar(32) NOT NULL,
  `OCCURRED_AT` datetime(3) NOT NULL,
  `EVENT_TYPE` varchar(16) NOT NULL,
  `RESULT` varchar(16) NOT NULL,
  `REASON_CODE` varchar(40) NOT NULL,
  `ACCOUNT` varchar(16) DEFAULT NULL,
  `ACCOUNT_HASH` char(64) DEFAULT NULL,
  `USER_ID` varchar(32) DEFAULT NULL,
  `TENANT_ID` varchar(32) DEFAULT NULL,
  `ORG_ID` varchar(32) DEFAULT NULL,
  `IP_ADDRESS` varchar(45) NOT NULL,
  `BROWSER` varchar(48) NOT NULL,
  `DURATION_MS` bigint(20) NOT NULL,
  `TRACE_ID` varchar(32) NOT NULL,
  PRIMARY KEY (`LOG_ID`),
  KEY `IDX_LOGIN_LOG_TENANT_TIME` (`TENANT_ID`,`OCCURRED_AT`,`LOG_ID`),
  KEY `IDX_LOGIN_LOG_TIME` (`OCCURRED_AT`,`LOG_ID`),
  KEY `IDX_LOGIN_LOG_ACCOUNT_TIME` (`ACCOUNT_HASH`,`OCCURRED_AT`),
  KEY `IDX_LOGIN_LOG_IP_TIME` (`IP_ADDRESS`,`OCCURRED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='登录审计，只读查询与保留期清理';
