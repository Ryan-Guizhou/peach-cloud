CREATE TABLE PEACH_TENANT_INVITATION
(
    ID                     VARCHAR(32) NOT NULL COMMENT '物理主键',
    INVITATION_ID          VARCHAR(32) NOT NULL COMMENT '永久邀请业务ID',
    TENANT_REF_ID          VARCHAR(32) NOT NULL COMMENT '租户物理ID',
    INVITER_MEMBER_REF_ID  VARCHAR(32) NOT NULL COMMENT '邀请人租户成员物理ID',
    INVITEE_USER_REF_ID    VARCHAR(32) NOT NULL COMMENT '受邀全局用户物理ID',
    STATUS                 VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING ACCEPTED REJECTED EXPIRED CANCELLED',
    EXPIRES_AT             DATETIME(3) NOT NULL COMMENT '邀请过期时间',
    IS_DELETE              TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    ACTIVE_SLOT            TINYINT GENERATED ALWAYS AS (
        CASE WHEN IS_DELETE = 0 AND STATUS = 'PENDING' THEN 1 ELSE NULL END
    ) STORED,
    CREATED_TIME           VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID             VARCHAR(32) NULL COMMENT '创建人ID',
    MODIFY_TIME            VARCHAR(20) NULL COMMENT '修改时间',
    MODIFIER_ID            VARCHAR(32) NULL COMMENT '修改人ID',
    DELETED_AT             DATETIME(3) NULL COMMENT '删除时间',
    DELETED_BY_REF_ID      VARCHAR(32) NULL COMMENT '删除操作者物理ID',
    VERSION                BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_INVITATION_BIZ (INVITATION_ID),
    UNIQUE KEY UK_INVITATION_PENDING (TENANT_REF_ID, INVITEE_USER_REF_ID, ACTIVE_SLOT),
    KEY IDX_INVITATION_MEMBER (INVITER_MEMBER_REF_ID, STATUS),
    KEY IDX_INVITATION_EXPIRY (STATUS, EXPIRES_AT)
) COMMENT='租户成员邀请表';
