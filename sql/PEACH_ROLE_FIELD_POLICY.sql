CREATE TABLE PEACH_ROLE_FIELD_POLICY
(
    ID                  VARCHAR(32) NOT NULL COMMENT 'UUID物理主键',
    TENANT_REF_ID       VARCHAR(32) NOT NULL COMMENT '物理租户ID',
    APP_REF_ID          VARCHAR(32) NOT NULL COMMENT '物理应用ID',
    ROLE_REF_ID         VARCHAR(32) NOT NULL COMMENT '物理角色ID',
    PERMISSION_REF_ID   VARCHAR(32) NOT NULL COMMENT '角色动作权限物理ID',
    FIELD_REF_ID        VARCHAR(32) NOT NULL COMMENT '字段定义物理ID',
    READ_EFFECT         VARCHAR(16) NOT NULL DEFAULT 'DENY' COMMENT 'ALLOW MASK DENY',
    WRITE_EFFECT        VARCHAR(16) NOT NULL DEFAULT 'DENY' COMMENT 'ALLOW DENY',
    STATUS              VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED',
    IS_DELETE           TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    VERSION             BIGINT NOT NULL DEFAULT 0 COMMENT '乐观版本',
    ACTIVE_SLOT         TINYINT GENERATED ALWAYS AS (CASE WHEN IS_DELETE = 0 THEN 1 ELSE NULL END) STORED,
    CREATED_TIME        VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID          VARCHAR(32) NULL COMMENT '创建人成员物理ID',
    DELETED_AT          DATETIME(3) NULL COMMENT '删除时间',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_ROLE_FIELD_POLICY_ACTIVE (ROLE_REF_ID, PERMISSION_REF_ID, FIELD_REF_ID, ACTIVE_SLOT),
    KEY IDX_ROLE_FIELD_POLICY_ACTION (TENANT_REF_ID, APP_REF_ID, ROLE_REF_ID, PERMISSION_REF_ID, STATUS, IS_DELETE),
    CONSTRAINT CK_ROLE_FIELD_READ CHECK (READ_EFFECT IN ('ALLOW','MASK','DENY')),
    CONSTRAINT CK_ROLE_FIELD_WRITE CHECK (WRITE_EFFECT IN ('ALLOW','DENY')),
    CONSTRAINT CK_ROLE_FIELD_STATUS CHECK (STATUS IN ('ACTIVE','DISABLED'))
) COMMENT='按同一角色动作配置字段读写规则，未定义默认拒绝';
