CREATE TABLE PEACH_SAAS_UI_RESOURCE
(
    ID                   VARCHAR(32) NOT NULL COMMENT 'UI目录映射物理主键',
    PERMISSION_REF_ID    VARCHAR(32) NOT NULL COMMENT 'MENU权限定义物理ID',
    MENU_CODE            VARCHAR(64) NOT NULL COMMENT '前端菜单稳定标识',
    MENU_NAME            VARCHAR(64) NOT NULL COMMENT '前端菜单展示名称',
    MENU_ICON            VARCHAR(64) NULL COMMENT '前端展示图标',
    ROUTER_CODE          VARCHAR(64) NOT NULL COMMENT '前端路由稳定标识',
    ROUTER_URL           VARCHAR(128) NOT NULL COMMENT '规范化前端路由路径',
    FILE_PATH            VARCHAR(255) NOT NULL COMMENT '前端构建期组件标识，不执行任意代码',
    STATUS               VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED',
    IS_DELETE            TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    ACTIVE_SLOT          TINYINT GENERATED ALWAYS AS (CASE WHEN IS_DELETE = 0 THEN 1 ELSE NULL END) STORED,
    CREATED_TIME         VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID           VARCHAR(32) NULL COMMENT '创建人物理ID',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_SAAS_UI_PERMISSION_ACTIVE (PERMISSION_REF_ID, ACTIVE_SLOT),
    KEY IDX_SAAS_UI_PERMISSION_STATE (PERMISSION_REF_ID, STATUS, IS_DELETE),
    CONSTRAINT CK_SAAS_UI_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT CK_SAAS_UI_DELETED CHECK (IS_DELETE IN (0, 1))
) COMMENT='基于权限物理主键的受信菜单与路由映射；仅显式授予的MENU权限可展示';
