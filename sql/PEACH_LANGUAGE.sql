CREATE TABLE `PEACH_LANGUAGE` (
  `ID` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '语言ID',
  `LANGUAGE_CODE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '语言编码',
  `LANGUAGE_NAME` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '语言名称',
  `NATIVE_NAME` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '本地化名称',
  `ICON` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '语言图标',
  `STATUS` int(11) DEFAULT NULL COMMENT '状态',
  `DEFAULT_FLAG` int(11) DEFAULT NULL COMMENT '是否默认',
  `SORT_ORDER` int(11) DEFAULT NULL COMMENT '排序',
  `TENANT_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '租户ID',
  `ORG_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '机构ID',
  `CREATED_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建时间',
  `CREATOR_ID` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建人ID',
  `MODIFY_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改时间',
  `MODIFIER_ID` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改人ID',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_LANGUAGE_CONTEXT_CODE` (`TENANT_ID`,`ORG_ID`,`LANGUAGE_CODE`),
  KEY `IDX_LANGUAGE_CONTEXT` (`TENANT_ID`,`ORG_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='语言设置表';
