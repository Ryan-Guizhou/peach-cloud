CREATE TABLE PEACH_ROLE_PERMISSION
(
    ID                 VARCHAR(32) NOT NULL COMMENT '物理主键',
    TENANT_REF_ID      VARCHAR(32) NOT NULL COMMENT '租户物理ID',
    ROLE_REF_ID        VARCHAR(32) NOT NULL COMMENT '角色物理ID',
    PERMISSION_REF_ID  VARCHAR(32) NOT NULL COMMENT '权限物理ID',
    STATUS             VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED',
    IS_DELETE          TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    VERSION            BIGINT NOT NULL DEFAULT 0 COMMENT '乐观版本',
    ACTIVE_SLOT        TINYINT GENERATED ALWAYS AS (CASE WHEN IS_DELETE = 0 THEN 1 ELSE NULL END) STORED,
    CREATED_TIME       VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID         VARCHAR(32) NULL COMMENT '创建人物理ID',
    DELETED_AT         DATETIME(3) NULL COMMENT '逻辑删除时间',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_ROLE_PERMISSION_ACTIVE (ROLE_REF_ID, PERMISSION_REF_ID, ACTIVE_SLOT),
    KEY IDX_ROLE_PERMISSION_TENANT (TENANT_REF_ID, ROLE_REF_ID, STATUS, IS_DELETE),
    CONSTRAINT CK_ROLE_PERMISSION_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED'))
) COMMENT='角色权限关系，授权只由角色关联生效';
