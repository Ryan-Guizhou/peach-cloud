CREATE TABLE PEACH_FIELD_DEFINITION
(
    ID                  VARCHAR(32) NOT NULL COMMENT 'UUID物理主键',
    FIELD_ID            VARCHAR(32) NOT NULL COMMENT '永不复用的字段业务ID',
    TENANT_REF_ID       VARCHAR(32) NULL COMMENT '租户字段所属物理租户ID；平台字段为空',
    APP_REF_ID          VARCHAR(32) NULL COMMENT '字段所属物理应用ID；公共字段为空',
    OWNER_TYPE          VARCHAR(16) NOT NULL COMMENT 'SYSTEM TENANT',
    RESOURCE_CODE       VARCHAR(64) NOT NULL COMMENT '服务端注册的稳定资源类型',
    FIELD_CODE          VARCHAR(64) NOT NULL COMMENT '服务端受控JSON字段名',
    MASK_STRATEGY       VARCHAR(16) NOT NULL DEFAULT 'FULL' COMMENT 'FULL PHONE EMAIL',
    STATUS              VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED',
    IS_DELETE           TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    VERSION             BIGINT NOT NULL DEFAULT 0 COMMENT '乐观版本',
    DELETED_AT          DATETIME(3) NULL COMMENT '逻辑删除时间',
    ACTIVE_SLOT         TINYINT GENERATED ALWAYS AS (CASE WHEN IS_DELETE = 0 THEN 1 ELSE NULL END) STORED,
    TENANT_KEY          VARCHAR(32) GENERATED ALWAYS AS (COALESCE(TENANT_REF_ID, 'PLATFORM')) STORED,
    APP_KEY             VARCHAR(32) GENERATED ALWAYS AS (COALESCE(APP_REF_ID, 'GLOBAL')) STORED,
    CREATED_TIME        VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID          VARCHAR(32) NULL COMMENT '创建人成员物理ID',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FIELD_BIZ_ID (FIELD_ID),
    UNIQUE KEY UK_FIELD_SEMANTIC (TENANT_KEY, APP_KEY, RESOURCE_CODE, FIELD_CODE, ACTIVE_SLOT),
    KEY IDX_FIELD_DEFINITION_LOOKUP (TENANT_REF_ID, APP_REF_ID, RESOURCE_CODE, STATUS, IS_DELETE),
    CONSTRAINT CK_FIELD_OWNER_TYPE CHECK (OWNER_TYPE IN ('SYSTEM', 'TENANT')),
    CONSTRAINT CK_FIELD_OWNER_SCOPE CHECK (
        (OWNER_TYPE = 'SYSTEM' AND TENANT_REF_ID IS NULL)
        OR (OWNER_TYPE = 'TENANT' AND TENANT_REF_ID IS NOT NULL)),
    CONSTRAINT CK_FIELD_MASK_STRATEGY CHECK (MASK_STRATEGY IN ('FULL','PHONE','EMAIL')),
    CONSTRAINT CK_FIELD_DEFINITION_STATUS CHECK (STATUS IN ('ACTIVE','DISABLED'))
) COMMENT='后端受控字段目录；客户端字段参数不得直接成为SQL列名';
