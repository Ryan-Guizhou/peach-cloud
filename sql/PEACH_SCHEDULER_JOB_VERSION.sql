CREATE TABLE PEACH_SCHEDULER_JOB_VERSION
(
    ID                     BIGINT       NOT NULL AUTO_INCREMENT COMMENT '快照主键',
    JOB_ID                 BIGINT       NOT NULL COMMENT '任务主键',
    SCHEDULE_VERSION       BIGINT       NOT NULL COMMENT '调度定义版本号',
    JOB_CODE               VARCHAR(128) NOT NULL COMMENT '稳定任务编码',
    APPLICATION_NAME       VARCHAR(128) NOT NULL COMMENT '目标业务应用名称',
    HANDLER_NAME           VARCHAR(128) NOT NULL COMMENT '目标 Handler 名称',
    SCHEDULE_TYPE          VARCHAR(32)  NOT NULL COMMENT '调度类型',
    CRON_EXPRESSION        VARCHAR(128) NULL COMMENT 'Quartz Cron 表达式',
    INTERVAL_SECONDS       BIGINT       NULL COMMENT '固定周期秒数',
    START_AT               DATETIME(3)  NULL COMMENT '调度起始时间',
    TIME_ZONE              VARCHAR(64)  NOT NULL COMMENT '调度时区',
    MISFIRE_POLICY         VARCHAR(32)  NOT NULL COMMENT '错过触发策略',
    CONCURRENCY_POLICY     VARCHAR(32)  NOT NULL COMMENT '并发策略',
    TIMEOUT_MS             BIGINT       NOT NULL COMMENT '单次执行超时毫秒数',
    MAX_ATTEMPTS           INT          NOT NULL COMMENT '最大执行次数',
    RETRY_INTERVAL_SECONDS INT          NOT NULL COMMENT '重试间隔秒数',
    PARAMETERS_JSON        LONGTEXT     NULL COMMENT '任务参数 JSON',
    STATE                  VARCHAR(32)  NOT NULL COMMENT '快照时刻任务状态',
    CREATED_TIME           DATETIME(3)  NOT NULL COMMENT '快照创建时间',
    CREATOR_ID             VARCHAR(64)  NULL COMMENT '快照创建人 ID',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_SCHEDULER_JOB_VERSION (JOB_ID, SCHEDULE_VERSION),
    KEY IDX_SCHEDULER_JOB_VERSION_CODE (JOB_CODE),
    KEY IDX_SCHEDULER_JOB_VERSION_TIME (CREATED_TIME)
) COMMENT='调度任务定义版本快照表';
