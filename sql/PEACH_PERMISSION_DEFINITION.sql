CREATE TABLE PEACH_PERMISSION_DEFINITION
(
    ID                 VARCHAR(32) NOT NULL COMMENT '物理主键',
    PERMISSION_ID      VARCHAR(32) NOT NULL COMMENT '永久业务权限ID',
    TENANT_REF_ID      VARCHAR(32) NULL COMMENT '租户物理ID，系统权限为空',
    APP_REF_ID         VARCHAR(32) NULL COMMENT '应用物理ID，平台公共权限为空',
    PERMISSION_CODE    VARCHAR(128) NOT NULL COMMENT '不可复用的稳定权限语义码',
    PERMISSION_NAME    VARCHAR(128) NOT NULL COMMENT '权限名称',
    RESOURCE_TYPE      VARCHAR(16) NOT NULL COMMENT 'MENU BUTTON API OBJECT DATA FIELD',
    OWNER_TYPE         VARCHAR(16) NOT NULL COMMENT 'SYSTEM TENANT',
    DELEGABLE          TINYINT NOT NULL DEFAULT 0 COMMENT '租户管理员能否委派',
    STATUS             VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED',
    IS_DELETE          TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    VERSION            BIGINT NOT NULL DEFAULT 0 COMMENT '乐观版本',
    TENANT_KEY         VARCHAR(32) GENERATED ALWAYS AS (COALESCE(TENANT_REF_ID, 'PLATFORM')) STORED,
    APP_KEY            VARCHAR(32) GENERATED ALWAYS AS (COALESCE(APP_REF_ID, 'GLOBAL')) STORED,
    CREATED_TIME       VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID         VARCHAR(32) NULL COMMENT '创建人物理ID',
    DELETED_AT         DATETIME(3) NULL COMMENT '逻辑删除时间',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_PERMISSION_BIZ_ID (PERMISSION_ID),
    UNIQUE KEY UK_PERMISSION_SEMANTIC (TENANT_KEY, APP_KEY, PERMISSION_CODE),
    KEY IDX_PERMISSION_OWNER (TENANT_REF_ID, APP_REF_ID, STATUS, IS_DELETE),
    CONSTRAINT CK_PERMISSION_TYPE CHECK (RESOURCE_TYPE IN ('MENU', 'BUTTON', 'API', 'OBJECT', 'DATA', 'FIELD')),
    CONSTRAINT CK_PERMISSION_OWNER CHECK (OWNER_TYPE IN ('SYSTEM', 'TENANT')),
    CONSTRAINT CK_PERMISSION_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT CK_PERMISSION_DELEGATE CHECK (DELEGABLE IN (0, 1))
) COMMENT='权限语义目录；固定权限代码不可变更或重用';
