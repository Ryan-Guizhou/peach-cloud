CREATE TABLE `PEACH_RESOURCE` (
  `RESOURCE_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '资源ID',
  `FUNC_CODE` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '功能编码',
  `RESOURCE_TYPE` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '资源类型',
  `RESOURCE_CODE` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '资源编码',
  `RESOURCE_NAME` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '资源名称',
  `TENANT_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '租户ID',
  `APP_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '应用ID',
  `CREATED_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建时间',
