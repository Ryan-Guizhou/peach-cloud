CREATE TABLE `PEACH_SCHEDULER_EXECUTION_ATTEMPT` (
  `EXECUTION_ID` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '执行实例 ID',
  `ATTEMPT_NO` int(11) NOT NULL COMMENT '尝试序号',
  `EXECUTOR_INSTANCE` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '执行器实例标识',
  `STATE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '尝试状态',
  `START_TIME` datetime(3) NOT NULL COMMENT '尝试开始时间',
  `FINISH_TIME` datetime(3) DEFAULT NULL COMMENT '尝试结束时间',
  `DURATION_MS` bigint(20) DEFAULT NULL COMMENT '尝试耗时毫秒数',
  `ERROR_TYPE` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '失败类型',
  `ERROR_MESSAGE` varchar(1000) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '脱敏后的失败摘要',
  `CREATED_TIME` datetime(3) NOT NULL COMMENT '创建时间',
  PRIMARY KEY (`EXECUTION_ID`,`ATTEMPT_NO`),
  KEY `IDX_SCHEDULER_ATTEMPT_TIME` (`CREATED_TIME`),
  KEY `IDX_SCHEDULER_ATTEMPT_STATE` (`STATE`,`CREATED_TIME`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='调度执行尝试历史表';
