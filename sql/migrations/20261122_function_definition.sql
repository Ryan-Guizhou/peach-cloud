-- 功能定义：菜单改名与完整列表接口。可重复执行；不修改表结构。
START TRANSACTION;
UPDATE PEACH_FUNCTION SET FUNC_NAME = '功能定义' WHERE FUNC_CODE = 'SYS_FUNC_MGMT' AND FUNC_NAME IN ('功能管理', '功能定义字段');
UPDATE PEACH_MENU SET MENU_NAME = '功能定义' WHERE FUNC_CODE = 'SYS_FUNC_MGMT' AND MENU_NAME IN ('功能管理', '功能定义字段');
UPDATE PEACH_ROUTER SET ROUTER_NAME = '功能定义' WHERE FUNC_CODE = 'SYS_FUNC_MGMT' AND ROUTER_NAME IN ('功能管理', '功能定义字段');

INSERT INTO PEACH_RESOURCE (RESOURCE_ID, FUNC_CODE, RESOURCE_TYPE, RESOURCE_CODE, RESOURCE_NAME, TENANT_ID, APP_ID, IS_DELETE)
SELECT MD5(CONCAT('function:list:', r.TENANT_ID, ':', r.APP_ID)), r.FUNC_CODE, 'API', 'POST:/api/auth/function/list', '查询完整功能定义', r.TENANT_ID, r.APP_ID, 0
FROM PEACH_RESOURCE r
WHERE r.FUNC_CODE = 'SYS_FUNC_MGMT' AND r.RESOURCE_CODE = 'POST:/api/auth/function/pageList' AND r.IS_DELETE = 0
  AND NOT EXISTS (SELECT 1 FROM PEACH_RESOURCE n WHERE n.TENANT_ID = r.TENANT_ID AND n.APP_ID = r.APP_ID AND n.FUNC_CODE = r.FUNC_CODE AND n.RESOURCE_CODE = 'POST:/api/auth/function/list');

INSERT INTO PEACH_AUTH_RESOURCE (RESOURCE_ID, TENANT_ID, ORG_ID, PARTY_CODE, FUNC_CODE, OP_TYPE, RESOURCE_CODE, RESOURCE_NAME, APP_ID, IS_DELETE, FISCAL)
SELECT MD5(CONCAT('function:list:', a.RESOURCE_ID)), a.TENANT_ID, a.ORG_ID, a.PARTY_CODE, a.FUNC_CODE, 'API', 'POST:/api/auth/function/list', '查询完整功能定义', a.APP_ID, 0, a.FISCAL
FROM PEACH_AUTH_RESOURCE a
WHERE a.FUNC_CODE = 'SYS_FUNC_MGMT' AND a.RESOURCE_CODE = 'POST:/api/auth/function/pageList' AND a.IS_DELETE = 0
  AND NOT EXISTS (SELECT 1 FROM PEACH_AUTH_RESOURCE n WHERE n.TENANT_ID = a.TENANT_ID AND n.APP_ID = a.APP_ID AND n.ORG_ID = a.ORG_ID AND n.PARTY_CODE = a.PARTY_CODE AND n.FISCAL = a.FISCAL AND n.FUNC_CODE = a.FUNC_CODE AND n.RESOURCE_CODE = 'POST:/api/auth/function/list');
COMMIT;
