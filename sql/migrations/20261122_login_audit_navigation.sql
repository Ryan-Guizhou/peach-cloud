-- 功能分类及登录审计。DDL 会隐式提交；后续数据迁移在独立事务中执行。
CREATE TABLE IF NOT EXISTS PEACH_LOGIN_LOG (
    LOG_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    OCCURRED_AT DATETIME(3) NOT NULL,
    EVENT_TYPE VARCHAR(16) NOT NULL,
    RESULT VARCHAR(16) NOT NULL,
    REASON_CODE VARCHAR(40) NOT NULL,
    ACCOUNT VARCHAR(16) NULL,
    ACCOUNT_HASH CHAR(64) NULL,
    USER_ID VARCHAR(32) NULL,
    TENANT_ID VARCHAR(32) NULL,
    ORG_ID VARCHAR(32) NULL,
    IP_ADDRESS VARCHAR(45) NOT NULL,
    BROWSER VARCHAR(48) NOT NULL,
    DURATION_MS BIGINT NOT NULL,
    TRACE_ID VARCHAR(32) NOT NULL,
    INDEX IDX_LOGIN_LOG_TENANT_TIME (TENANT_ID, OCCURRED_AT, LOG_ID),
    INDEX IDX_LOGIN_LOG_TIME (OCCURRED_AT, LOG_ID),
    INDEX IDX_LOGIN_LOG_ACCOUNT_TIME (ACCOUNT_HASH, OCCURRED_AT),
    INDEX IDX_LOGIN_LOG_IP_TIME (IP_ADDRESS, OCCURRED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='登录审计，只读查询与保留期清理';

START TRANSACTION;
-- 每个现有租户建立统一功能根及四个一级分类；保留所有业务编码与授权。
INSERT INTO PEACH_FUNCTION (FUNC_ID,FUNC_CODE,PARENT_FUNC_CODE,FUNC_NAME,FUNC_SEQ,FUNC_TYPE,IS_MENU,IS_AUTHORIZE,TENANT_ID,IS_DISABLE,IS_DELETE)
SELECT MD5(CONCAT('nav:',s.TENANT_ID,':',d.CODE)),d.CODE,d.PARENT,d.NAME,d.SEQ,'CATALOG',d.IS_MENU,0,s.TENANT_ID,0,0
FROM PEACH_FUNCTION s CROSS JOIN (
 SELECT 'FUNCTION_LIST_ROOT' CODE,NULL PARENT,'功能列表' NAME,'000' SEQ,0 IS_MENU UNION ALL
 SELECT 'SYS_AUDIT','FUNCTION_LIST_ROOT','日志审计','002',1 UNION ALL
 SELECT 'SYS_STORAGE','FUNCTION_LIST_ROOT','文件与存储','003',1 UNION ALL
 SELECT 'SYS_SCHEDULER','FUNCTION_LIST_ROOT','任务调度','004',1
) d
WHERE s.FUNC_CODE='SYS_SETTING' AND s.IS_DELETE=0
AND NOT EXISTS (SELECT 1 FROM PEACH_FUNCTION n WHERE n.TENANT_ID=s.TENANT_ID AND n.FUNC_CODE=d.CODE);
UPDATE PEACH_FUNCTION SET PARENT_FUNC_CODE='FUNCTION_LIST_ROOT',FUNC_SEQ='001' WHERE FUNC_CODE='SYS_SETTING' AND IS_DELETE=0;
UPDATE PEACH_FUNCTION SET PARENT_FUNC_CODE='SYS_AUDIT',FUNC_SEQ=CONCAT('002',RIGHT(COALESCE(NULLIF(FUNC_SEQ,''),'000'),3)) WHERE FUNC_CODE IN ('SYS_AUTH_LOG','SYS_OPER_LOG') AND IS_DELETE=0;
UPDATE PEACH_FUNCTION SET PARENT_FUNC_CODE='SYS_STORAGE',FUNC_SEQ=CONCAT('003',RIGHT(COALESCE(NULLIF(FUNC_SEQ,''),'000'),3)) WHERE FUNC_CODE IN ('SYS_FILE_RECORD','SYS_STORAGE_INSTANCE','SYS_OBJECT_BROWSER') AND IS_DELETE=0;
UPDATE PEACH_FUNCTION SET PARENT_FUNC_CODE='SYS_SCHEDULER',FUNC_SEQ=CONCAT('004',RIGHT(COALESCE(NULLIF(FUNC_SEQ,''),'000'),3)) WHERE FUNC_CODE IN ('SYS_SCHEDULER_JOB','SYS_SCHEDULER_EXECUTION','SYS_SCHEDULER_HANDLER') AND IS_DELETE=0;

INSERT INTO PEACH_MENU (MENU_ID,MENU_CODE,MENU_NAME,IS_LEAF,MENU_LEVEL,SORT_NO,MENU_SEQ,FUNC_CODE,TENANT_ID,IS_DELETE,IS_DISABLE,IS_SHOW)
SELECT MD5(CONCAT('nav-menu:',f.TENANT_ID,':',f.FUNC_CODE)),f.FUNC_CODE,f.FUNC_NAME,0,'1',RIGHT(f.FUNC_SEQ,1),f.FUNC_SEQ,f.FUNC_CODE,f.TENANT_ID,0,0,1
FROM PEACH_FUNCTION f WHERE f.FUNC_CODE IN ('SYS_AUDIT','SYS_STORAGE','SYS_SCHEDULER') AND f.IS_DELETE=0
AND NOT EXISTS (SELECT 1 FROM PEACH_MENU m WHERE m.TENANT_ID=f.TENANT_ID AND m.FUNC_CODE=f.FUNC_CODE);
UPDATE PEACH_MENU m JOIN PEACH_MENU g ON g.TENANT_ID=m.TENANT_ID AND g.FUNC_CODE='SYS_AUDIT' AND g.IS_DELETE=0
SET m.PARENT_MENU_ID=g.MENU_ID,m.MENU_LEVEL='2',m.MENU_SEQ=CONCAT('002',RIGHT(COALESCE(NULLIF(m.MENU_SEQ,''),'000'),3)) WHERE m.FUNC_CODE IN ('SYS_AUTH_LOG','SYS_OPER_LOG');
UPDATE PEACH_MENU m JOIN PEACH_MENU g ON g.TENANT_ID=m.TENANT_ID AND g.FUNC_CODE='SYS_STORAGE' AND g.IS_DELETE=0
SET m.PARENT_MENU_ID=g.MENU_ID,m.MENU_LEVEL='2',m.MENU_SEQ=CONCAT('003',RIGHT(COALESCE(NULLIF(m.MENU_SEQ,''),'000'),3)) WHERE m.FUNC_CODE IN ('SYS_FILE_RECORD','SYS_STORAGE_INSTANCE','SYS_OBJECT_BROWSER');
UPDATE PEACH_MENU m JOIN PEACH_MENU g ON g.TENANT_ID=m.TENANT_ID AND g.FUNC_CODE='SYS_SCHEDULER' AND g.IS_DELETE=0
SET m.PARENT_MENU_ID=g.MENU_ID,m.MENU_LEVEL='2',m.MENU_SEQ=CONCAT('004',RIGHT(COALESCE(NULLIF(m.MENU_SEQ,''),'000'),3)) WHERE m.FUNC_CODE IN ('SYS_SCHEDULER_JOB','SYS_SCHEDULER_EXECUTION','SYS_SCHEDULER_HANDLER');

INSERT INTO PEACH_FUNCTION (FUNC_ID,FUNC_CODE,PARENT_FUNC_CODE,FUNC_NAME,FUNC_URL,FUNC_SEQ,FUNC_TYPE,IS_MENU,IS_AUTHORIZE,TENANT_ID,IS_DISABLE,IS_DELETE)
SELECT MD5(CONCAT('login-log:',s.TENANT_ID)),'SYS_LOGIN_LOG','SYS_AUDIT','登录日志','/login-log','002001','MENU',1,1,s.TENANT_ID,0,0
FROM PEACH_FUNCTION s WHERE s.FUNC_CODE='SYS_AUDIT' AND s.IS_DELETE=0 AND NOT EXISTS (SELECT 1 FROM PEACH_FUNCTION n WHERE n.TENANT_ID=s.TENANT_ID AND n.FUNC_CODE='SYS_LOGIN_LOG');
INSERT INTO PEACH_MENU (MENU_ID,MENU_NAME,MENU_CODE,IS_LEAF,MENU_URL,PARENT_MENU_ID,MENU_LEVEL,SORT_NO,MENU_SEQ,FUNC_CODE,TENANT_ID,IS_DELETE,IS_DISABLE,IS_SHOW)
SELECT MD5(CONCAT('login-log-menu:',s.TENANT_ID)),'登录日志','loginLog',1,'/login-log',s.MENU_ID,'2','1','002001','SYS_LOGIN_LOG',s.TENANT_ID,0,0,1
FROM PEACH_MENU s WHERE s.FUNC_CODE='SYS_AUDIT' AND s.IS_DELETE=0 AND NOT EXISTS (SELECT 1 FROM PEACH_MENU n WHERE n.TENANT_ID=s.TENANT_ID AND n.MENU_CODE='loginLog');
INSERT INTO PEACH_ROUTER (ROUTER_ID,ROUTER_CODE,ROUTER_NAME,ROUTER_URL,FILE_PATH,FUNC_CODE,IS_AUTH,IS_CACHE,MODULE_CODE,ROUTER_LEVEL,TENANT_ID)
SELECT MD5(CONCAT('login-log-router:',s.TENANT_ID)),'SYS_LOGIN_LOG','登录日志','/login-log','log/login','SYS_LOGIN_LOG',1,0,'log',2,s.TENANT_ID
FROM PEACH_FUNCTION s WHERE s.FUNC_CODE='SYS_LOGIN_LOG' AND s.IS_DELETE=0 AND NOT EXISTS (SELECT 1 FROM PEACH_ROUTER n WHERE n.TENANT_ID=s.TENANT_ID AND n.ROUTER_URL='/login-log');
INSERT INTO PEACH_RESOURCE (RESOURCE_ID,FUNC_CODE,RESOURCE_TYPE,RESOURCE_CODE,RESOURCE_NAME,TENANT_ID,IS_DELETE)
SELECT MD5(CONCAT('login-log-resource:',f.TENANT_ID,':',d.CODE)),f.FUNC_CODE,d.TYPE,d.CODE,d.NAME,f.TENANT_ID,0
FROM PEACH_FUNCTION f CROSS JOIN (
 SELECT 'BUTTON' TYPE,'loginLog:view' CODE,'查看登录日志' NAME UNION ALL
 SELECT 'BUTTON','loginLog:platform','审计未归属登录事件' UNION ALL
 SELECT 'API','POST:/api/auth/loginLog/pageList','查询登录日志' UNION ALL
 SELECT 'API','GET:/api/auth/loginLog/selectById','查询登录日志详情'
) d WHERE f.FUNC_CODE='SYS_LOGIN_LOG' AND f.IS_DELETE=0 AND NOT EXISTS (SELECT 1 FROM PEACH_RESOURCE n WHERE n.TENANT_ID=f.TENANT_ID AND n.FUNC_CODE=f.FUNC_CODE AND n.RESOURCE_CODE=d.CODE);
-- 仅向已有授权日志访问者补充登录日志查看授权，不自动授予普通用户。
INSERT INTO PEACH_AUTH_FUNCTION (ID,TENANT_ID,ORG_ID,PARTY_CODE,PARTY_TYPE,FUNC_CODE,STATE,IS_DELETE)
SELECT MD5(CONCAT('login-log-auth:',a.ID)),a.TENANT_ID,a.ORG_ID,a.PARTY_CODE,a.PARTY_TYPE,'SYS_LOGIN_LOG',a.STATE,0
FROM PEACH_AUTH_FUNCTION a WHERE a.FUNC_CODE='SYS_AUTH_LOG' AND a.IS_DELETE=0
AND NOT EXISTS (SELECT 1 FROM PEACH_AUTH_FUNCTION n WHERE n.TENANT_ID=a.TENANT_ID AND n.ORG_ID=a.ORG_ID AND n.PARTY_CODE=a.PARTY_CODE AND n.PARTY_TYPE=a.PARTY_TYPE AND n.FUNC_CODE='SYS_LOGIN_LOG');
INSERT INTO PEACH_AUTH_RESOURCE (RESOURCE_ID,TENANT_ID,ORG_ID,PARTY_CODE,FUNC_CODE,OP_TYPE,RESOURCE_CODE,RESOURCE_NAME,IS_DELETE)
SELECT MD5(CONCAT('login-log-grant:',a.RESOURCE_ID,':',r.RESOURCE_CODE)),a.TENANT_ID,a.ORG_ID,a.PARTY_CODE,r.FUNC_CODE,r.RESOURCE_TYPE,r.RESOURCE_CODE,r.RESOURCE_NAME,0
FROM PEACH_AUTH_RESOURCE a JOIN PEACH_RESOURCE r ON r.TENANT_ID=a.TENANT_ID AND r.FUNC_CODE='SYS_LOGIN_LOG' AND r.IS_DELETE=0
WHERE a.FUNC_CODE='SYS_AUTH_LOG' AND a.RESOURCE_CODE='authLog:view' AND a.IS_DELETE=0
AND (r.RESOURCE_CODE!='loginLog:platform' OR (a.TENANT_ID='0a8e3d5f7c4b4e3a9d2c1b0f8e6a5c4d' AND a.ORG_ID='1b9f4e6a8d3c4f2b9a7e5d1c0b8f6a4e' AND a.PARTY_CODE='ROLE_SYS_ADMIN'))
AND NOT EXISTS (SELECT 1 FROM PEACH_AUTH_RESOURCE n WHERE n.TENANT_ID=a.TENANT_ID AND n.ORG_ID=a.ORG_ID AND n.PARTY_CODE=a.PARTY_CODE AND n.FUNC_CODE=r.FUNC_CODE AND n.RESOURCE_CODE=r.RESOURCE_CODE);
-- 修复历史租户路由，不改变现有授权。
UPDATE PEACH_ROUTER SET FUNC_CODE='SYS_TENANT_MGMT' WHERE ROUTER_CODE='SYS_TENANT_MGMT' AND ROUTER_URL='/tenant' AND FILE_PATH='system/tenant' AND (FUNC_CODE IS NULL OR FUNC_CODE='');
COMMIT;
