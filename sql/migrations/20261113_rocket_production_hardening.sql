-- 在 20261112 owner token 与 20261113 发送选项迁移之后执行一次。
-- 新库直接使用 sql/MQ_CONSUME_RECORD.sql 与 sql/MQ_OUTBOX_EVENT.sql，禁止把本脚本套到新库或已迁移库上。
-- EXPIRES_AT 为空时保留历史 SUCCESS 记录，直到运维按保留期回填；不得用本脚本清空幂等或待发送数据。
-- utf8mb4_bin 区分大小写。改排序规则前停止生产者、消费者和 Outbox Dispatcher，并确认唯一键不存在仅大小写不同的重复值。
-- 本脚本会重建相关索引，须在备份和预演之后由独立迁移账号执行。

ALTER TABLE MQ_CONSUME_RECORD
    ADD COLUMN EXPIRES_AT DATETIME(3) NULL COMMENT '成功幂等记录的保留截止时间';

ALTER TABLE MQ_CONSUME_RECORD
    ENGINE=InnoDB,
    DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin,
    MODIFY IDEMPOTENT_KEY VARCHAR(256) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '幂等键',
    MODIFY CONSUMER_GROUP VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '消费者组',
    MODIFY MESSAGE_ID VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT '消息 ID',
    MODIFY OWNER_TOKEN VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT '当前认领者令牌';

ALTER TABLE MQ_OUTBOX_EVENT
    ENGINE=InnoDB,
    DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin,
    MODIFY MESSAGE_ID VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '消息唯一 ID',
    MODIFY CLAIMED_BY VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT 'Outbox 抢占实例标识',
    MODIFY BROKER_MESSAGE_ID VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT 'Broker 返回的消息 ID';
