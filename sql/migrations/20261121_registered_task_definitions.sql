-- Replace only untouched backend-generated placeholder drafts with real definitions.
-- Keep task IDs and historical snapshots. Repeated execution is a no-op.
START TRANSACTION;
UPDATE PEACH_SCHEDULER_JOB
SET JOB_CODE = CASE APPLICATION_NAME
        WHEN 'peach-auth' THEN 'auth_scheduler_cron_demo'
        WHEN 'peach-setting' THEN 'setting_scheduler_interval_demo' END,
    JOB_NAME = CASE APPLICATION_NAME WHEN 'peach-auth' THEN 'Auth Cron 联调测试'
        WHEN 'peach-setting' THEN 'Setting 固定周期联调测试' END,
    SCHEDULE_TYPE = CASE APPLICATION_NAME WHEN 'peach-auth' THEN 'CRON' ELSE 'FIXED_INTERVAL' END,
    CRON_EXPRESSION = CASE APPLICATION_NAME WHEN 'peach-auth' THEN '0 * * * * ?' ELSE NULL END,
    INTERVAL_SECONDS = CASE APPLICATION_NAME WHEN 'peach-setting' THEN 60 ELSE NULL END,
    TIME_ZONE = 'Asia/Shanghai', MISFIRE_POLICY = 'SKIP', CONCURRENCY_POLICY = 'DISALLOW',
    TIMEOUT_MS = 30000, MAX_ATTEMPTS = 1, RETRY_INTERVAL_SECONDS = 10, PARAMETERS_JSON = '{}',
    VERSION = VERSION + 1, SCHEDULE_VERSION = SCHEDULE_VERSION + 1,
    SYNC_STATUS = 'SYNCED', MODIFY_TIME = NOW(3)
WHERE CREATOR_ID = 'handler-registration' AND MODIFIER_ID = 'handler-registration'
  AND STATE = 'DRAFT' AND VERSION = 0
  AND ((APPLICATION_NAME = 'peach-auth' AND HANDLER_NAME = 'authSchedulerDemo'
        AND JOB_CODE = 'registered_53d1e7dcedf537ecb9cfe2353436b369')
    OR (APPLICATION_NAME = 'peach-setting' AND HANDLER_NAME = 'settingSchedulerDemo'
        AND JOB_CODE = 'registered_3304e04a732c39728bc56c0d058afede'));

INSERT INTO PEACH_SCHEDULER_JOB_VERSION
    (JOB_ID, SCHEDULE_VERSION, JOB_CODE, APPLICATION_NAME, HANDLER_NAME, SCHEDULE_TYPE,
     CRON_EXPRESSION, INTERVAL_SECONDS, START_AT, TIME_ZONE, MISFIRE_POLICY,
     CONCURRENCY_POLICY, TIMEOUT_MS, MAX_ATTEMPTS, RETRY_INTERVAL_SECONDS,
     PARAMETERS_JSON, STATE, CREATED_TIME, CREATOR_ID)
SELECT J.ID, J.SCHEDULE_VERSION, J.JOB_CODE, J.APPLICATION_NAME, J.HANDLER_NAME, J.SCHEDULE_TYPE,
       J.CRON_EXPRESSION, J.INTERVAL_SECONDS, J.START_AT, J.TIME_ZONE, J.MISFIRE_POLICY,
       J.CONCURRENCY_POLICY, J.TIMEOUT_MS, J.MAX_ATTEMPTS, J.RETRY_INTERVAL_SECONDS,
       J.PARAMETERS_JSON, J.STATE, NOW(3), 'handler-registration'
FROM PEACH_SCHEDULER_JOB J
WHERE J.CREATOR_ID = 'handler-registration' AND J.MODIFIER_ID = 'handler-registration'
  AND J.STATE = 'DRAFT' AND J.VERSION = 1 AND J.SCHEDULE_VERSION = 2
  AND J.JOB_CODE IN ('auth_scheduler_cron_demo', 'setting_scheduler_interval_demo')
  AND NOT EXISTS (SELECT 1 FROM PEACH_SCHEDULER_JOB_VERSION V
      WHERE V.JOB_ID = J.ID AND V.SCHEDULE_VERSION = J.SCHEDULE_VERSION);
COMMIT;
