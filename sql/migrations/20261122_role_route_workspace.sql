-- 默认菜单与路由URL长度对齐；DDL独立提交，数据迁移幂等。
ALTER TABLE PEACH_ROLE MODIFY SKIP_URL VARCHAR(100) NULL COMMENT '角色登录默认页面';
START TRANSACTION;
INSERT INTO PEACH_RESOURCE (RESOURCE_ID,FUNC_CODE,RESOURCE_TYPE,RESOURCE_CODE,RESOURCE_NAME,TENANT_ID,APP_ID,IS_DELETE)
SELECT MD5(CONCAT('role-workspace:',f.TENANT_ID,':',f.APP_ID,':',d.CODE)),f.FUNC_CODE,'API',d.CODE,d.NAME,f.TENANT_ID,f.APP_ID,0
FROM PEACH_FUNCTION f CROSS JOIN (
 SELECT 'GET:/api/auth/role/workspace' CODE,'查询角色授权快照' NAME UNION ALL
 SELECT 'GET:/api/auth/role/members','查询角色成员' UNION ALL
 SELECT 'POST:/api/auth/role/saveGrants','保存角色功能与资源授权' UNION ALL
 SELECT 'POST:/api/auth/role/calibrate','预览角色授权校准' UNION ALL
 SELECT 'POST:/api/auth/role/saveMembers','保存角色成员' UNION ALL
 SELECT 'POST:/api/auth/role/saveDefault','设置角色默认菜单'
) d WHERE f.FUNC_CODE='SYS_ROLE_MGMT' AND f.IS_DELETE=0 AND NOT EXISTS (SELECT 1 FROM PEACH_RESOURCE n WHERE n.TENANT_ID=f.TENANT_ID AND n.APP_ID=f.APP_ID AND n.FUNC_CODE=f.FUNC_CODE AND n.RESOURCE_CODE=d.CODE);
-- 依据现有按钮权限补API，不给仅查看角色的用户新增授权维护能力。
INSERT INTO PEACH_AUTH_RESOURCE (RESOURCE_ID,TENANT_ID,ORG_ID,PARTY_CODE,FUNC_CODE,OP_TYPE,RESOURCE_CODE,RESOURCE_NAME,APP_ID,IS_DELETE,FISCAL)
SELECT MD5(CONCAT('role-workspace-grant:',a.RESOURCE_ID,':',r.RESOURCE_CODE)),a.TENANT_ID,a.ORG_ID,a.PARTY_CODE,r.FUNC_CODE,'API',r.RESOURCE_CODE,r.RESOURCE_NAME,a.APP_ID,0,a.FISCAL
FROM PEACH_AUTH_RESOURCE a JOIN PEACH_RESOURCE r ON r.TENANT_ID=a.TENANT_ID AND r.APP_ID=a.APP_ID AND r.FUNC_CODE='SYS_ROLE_MGMT' AND r.IS_DELETE=0
WHERE a.OP_TYPE='BUTTON' AND a.IS_DELETE=0 AND (
 (a.RESOURCE_CODE='role:view' AND r.RESOURCE_CODE='GET:/api/auth/role/workspace') OR
 (a.RESOURCE_CODE='authorization:update' AND r.RESOURCE_CODE IN ('GET:/api/auth/role/members','POST:/api/auth/role/saveGrants','POST:/api/auth/role/calibrate','POST:/api/auth/role/saveMembers')) OR
 (a.RESOURCE_CODE='role:update' AND r.RESOURCE_CODE='POST:/api/auth/role/saveDefault')
) AND NOT EXISTS (SELECT 1 FROM PEACH_AUTH_RESOURCE n WHERE n.TENANT_ID=a.TENANT_ID AND n.ORG_ID=a.ORG_ID AND n.APP_ID=a.APP_ID AND n.PARTY_CODE=a.PARTY_CODE AND n.FISCAL=a.FISCAL AND n.FUNC_CODE=r.FUNC_CODE AND n.RESOURCE_CODE=r.RESOURCE_CODE);
COMMIT;
