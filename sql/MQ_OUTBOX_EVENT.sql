CREATE TABLE `MQ_OUTBOX_EVENT` (
  `ID` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键 ID',
  `MESSAGE_ID` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '消息唯一 ID',
  `TOPIC` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'RocketMQ Topic',
  `TAG` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'RocketMQ Tag',
  `BUSINESS_KEY` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '业务 Key，通常为 executionId',
  `PAYLOAD` longtext COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'Base64 编码后的标准消息 Envelope',
  `SEND_MODE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'NORMAL' COMMENT '发送模式：NORMAL、ORDERLY、DELAY',
  `SHARDING_KEY` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '顺序消息分片键',
  `DELAY_LEVEL` int(11) DEFAULT NULL COMMENT 'RocketMQ 延迟级别',
  `SEND_TIMEOUT_MS` bigint(20) DEFAULT NULL COMMENT '本次发送超时毫秒数，NULL 使用默认超时',
  `PAYLOAD_TYPE` varchar(256) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Payload 类型名称',
  `HEADERS` text COLLATE utf8mb4_unicode_ci COMMENT '消息 Headers 快照，禁止写入敏感字段',
  `STATUS` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '状态：INIT、SENDING、SENT、RETRY、FAILED',
  `RETRY_COUNT` int(11) NOT NULL DEFAULT '0' COMMENT '重试次数',
  `NEXT_RETRY_TIME` datetime(3) NOT NULL COMMENT '下次可重试时间',
  `LAST_ERROR` varchar(1000) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '脱敏后的最近错误',
  `BROKER_MESSAGE_ID` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Broker 返回的消息 ID',
  `CLAIMED_BY` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Outbox 抢占实例标识',
  `CLAIMED_AT` datetime(3) DEFAULT NULL COMMENT 'Outbox 抢占时间',
  `SENT_AT` datetime(3) DEFAULT NULL COMMENT '投递成功时间',
  `CREATED_AT` datetime(3) NOT NULL COMMENT '创建时间',
  `UPDATED_AT` datetime(3) NOT NULL COMMENT '更新时间',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_MQ_OUTBOX_MESSAGE` (`MESSAGE_ID`),
  KEY `IDX_MQ_OUTBOX_STATUS_RETRY` (`STATUS`,`NEXT_RETRY_TIME`),
  KEY `IDX_MQ_OUTBOX_STATUS_CLAIMED` (`STATUS`,`CLAIMED_AT`),
  KEY `IDX_MQ_OUTBOX_TOPIC_KEY` (`TOPIC`,`BUSINESS_KEY`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='RocketMQ JDBC Outbox 可靠消息表';
