CREATE TABLE PEACH_MENU
(
    MENU_ID          VARCHAR(32)  NOT NULL COMMENT '菜单ID',
    MENU_NAME        VARCHAR(40)      NULL COMMENT '菜单名称',
    MENU_CODE        VARCHAR(128)     NULL COMMENT '菜单编码',
    IS_LEAF          TINYINT(1)       NULL COMMENT '是否叶子',
    MENU_URL         VARCHAR(1500)    NULL COMMENT '菜单URL',
    MENU_PARAM       VARCHAR(100)     NULL COMMENT '菜单参数',
    PARENT_MENU_ID   VARCHAR(32)      NULL COMMENT '父菜单ID',
    MENU_LEVEL       MEDIUMTEXT       NULL COMMENT '菜单级别',
    SORT_NO          VARCHAR(3)       NULL COMMENT '显示顺序',
    COLLAPSE_ICON    VARCHAR(32)      NULL COMMENT '折叠图标',
    EXPAND_ICON      VARCHAR(32)      NULL COMMENT '展开图标',
    MENU_SEQ         VARCHAR(128)     NULL COMMENT '菜单序列',
    OPEN_MODE        VARCHAR(20)      NULL COMMENT '打开方式',
    SUBCOUNT         MEDIUMTEXT       NULL COMMENT '子菜单数量',
    FUNC_CODE        VARCHAR(128)     NULL COMMENT '功能编码',
    MENU_APP_ID      VARCHAR(64)      NULL COMMENT '菜单应用ID',
    TENANT_ID        VARCHAR(32)  NOT NULL COMMENT '租户ID',
    APP_ID           VARCHAR(32)  NOT NULL COMMENT '应用ID',
    CREATED_TIME     VARCHAR(20)      NULL COMMENT '创建时间',
    CREATOR_ID       VARCHAR(32)      NULL COMMENT '创建人ID',
    MODIFY_TIME      VARCHAR(20)      NULL COMMENT '修改时间',
    MODIFIER_ID      VARCHAR(32)      NULL COMMENT '修改人ID',
    IS_DELETE        TINYINT(1) DEFAULT 0  COMMENT '是否删除',
    IS_DISABLE       TINYINT(1) DEFAULT 0  COMMENT '菜单显示是否禁用',
    IS_SHOW          TINYINT(1) DEFAULT 0  COMMENT '是否显示:1显示,0不显示',
    SF_BLANK         TINYINT(1) DEFAULT 0  COMMENT '是否新页签打开菜单',
    MENU_ICON        VARCHAR(200)     NULL COMMENT '菜单图标',
    PRIMARY KEY (MENU_ID),
    UNIQUE KEY UK_MENU_TENANT_APP_CODE (TENANT_ID, APP_ID, MENU_CODE),
    INDEX IDX_MENU_TENANT_APP_PARENT (TENANT_ID, APP_ID, PARENT_MENU_ID),
    INDEX IDX_MENU_TENANT_APP_FUNC (TENANT_ID, APP_ID, FUNC_CODE)
) COMMENT='应用菜单表';
