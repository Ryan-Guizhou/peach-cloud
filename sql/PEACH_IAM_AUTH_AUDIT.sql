CREATE TABLE PEACH_IAM_AUTH_AUDIT
(
    ID                 VARCHAR(32) NOT NULL COMMENT '审计物理主键',
    TENANT_REF_ID      VARCHAR(32) NOT NULL COMMENT '租户物理ID',
    APP_REF_ID         VARCHAR(32) NULL COMMENT '应用物理ID',
    AUTH_YEAR          SMALLINT NULL COMMENT '自然年度',
    OPERATOR_REF_ID    VARCHAR(32) NOT NULL COMMENT '操作人成员物理ID',
    TARGET_REF_ID      VARCHAR(32) NOT NULL COMMENT '被修改对象物理ID',
    OPERATION          VARCHAR(32) NOT NULL COMMENT '授权变更操作码',
    OLD_VERSION        BIGINT NOT NULL COMMENT '旧授权版本',
    NEW_VERSION        BIGINT NOT NULL COMMENT '新授权版本',
    CREATED_AT         DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '变更时间',
    PRIMARY KEY (ID),
    KEY IDX_IAM_AUDIT_TENANT_TIME (TENANT_REF_ID, CREATED_AT),
    KEY IDX_IAM_AUDIT_TARGET (TARGET_REF_ID, OPERATION)
) COMMENT='IAM授权变更只追加审计';
