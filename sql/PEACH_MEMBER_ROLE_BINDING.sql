CREATE TABLE PEACH_MEMBER_ROLE_BINDING
(
    ID                 VARCHAR(32) NOT NULL COMMENT '物理主键',
    TENANT_REF_ID      VARCHAR(32) NOT NULL COMMENT '租户物理ID',
    MEMBER_REF_ID      VARCHAR(32) NOT NULL COMMENT '成员物理ID',
    APP_REF_ID         VARCHAR(32) NOT NULL COMMENT '应用物理ID',
    ROLE_REF_ID        VARCHAR(32) NOT NULL COMMENT '角色物理ID',
    SCOPE_TYPE         VARCHAR(16) NOT NULL COMMENT 'TENANT ORG ORG_TREE',
    SCOPE_REF_ID       VARCHAR(32) NULL COMMENT 'ORG/ORG_TREE 机构物理ID，TENANT为空',
    SCOPE_KEY          VARCHAR(32) GENERATED ALWAYS AS (COALESCE(SCOPE_REF_ID, 'TENANT')) STORED,
    STATUS             VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED',
    IS_DELETE          TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    VERSION            BIGINT NOT NULL DEFAULT 0 COMMENT '乐观版本',
    ACTIVE_SLOT        TINYINT GENERATED ALWAYS AS (CASE WHEN IS_DELETE = 0 THEN 1 ELSE NULL END) STORED,
    CREATED_TIME       VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID         VARCHAR(32) NULL COMMENT '创建人物理ID',
    DELETED_AT         DATETIME(3) NULL COMMENT '逻辑删除时间',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_MEMBER_ROLE_SCOPE_ACTIVE (TENANT_REF_ID, MEMBER_REF_ID, APP_REF_ID,
        ROLE_REF_ID, SCOPE_TYPE, SCOPE_KEY, ACTIVE_SLOT),
    KEY IDX_MEMBER_ROLE_DECISION (MEMBER_REF_ID, TENANT_REF_ID, APP_REF_ID, STATUS, IS_DELETE),
    CONSTRAINT CK_MEMBER_ROLE_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT CK_MEMBER_ROLE_SCOPE CHECK (
        (SCOPE_TYPE = 'TENANT' AND SCOPE_REF_ID IS NULL)
        OR (SCOPE_TYPE IN ('ORG', 'ORG_TREE') AND SCOPE_REF_ID IS NOT NULL))
) COMMENT='成员按租户、应用、独立机构范围挂载角色';
