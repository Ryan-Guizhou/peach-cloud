-- #232: One-time schema migration for existing PEACH_FILE_* tables.
-- First take a consistent backup and verify every old FILE_ID/OBJECT_ID/SESSION_ID is unique.
-- The added tenant/app/owner physical scope fields intentionally start NULL. Existing
-- records are NOT exposed until a separately reviewed source-of-truth mapping is complete.
-- Do not guess APP_REF_ID or owner from legacy TENANT_ID/ORG_ID or a client-supplied header.
-- This script is not idempotent; apply exactly once under the DBA change procedure.

ALTER TABLE PEACH_FILE_RECORD
    ADD COLUMN ID VARCHAR(32) NULL COMMENT 'UUID物理主键' FIRST,
    ADD COLUMN TENANT_REF_ID VARCHAR(32) NULL COMMENT '物理租户主键',
    ADD COLUMN APP_REF_ID VARCHAR(32) NULL COMMENT '物理应用主键',
    ADD COLUMN ORG_REF_ID VARCHAR(32) NULL COMMENT '物理机构主键',
    ADD COLUMN OWNER_USER_REF_ID VARCHAR(32) NULL COMMENT '所有者用户物理主键',
    MODIFY COLUMN ORG_ID VARCHAR(32) NULL COMMENT '旧机构业务号，兼容字段';

ALTER TABLE PEACH_FILE_OBJECT
    ADD COLUMN ID VARCHAR(32) NULL COMMENT 'UUID物理主键' FIRST,
    ADD COLUMN TENANT_REF_ID VARCHAR(32) NULL COMMENT '物理租户主键',
    ADD COLUMN APP_REF_ID VARCHAR(32) NULL COMMENT '物理应用主键',
    ADD COLUMN ORG_REF_ID VARCHAR(32) NULL COMMENT '物理机构主键',
    ADD COLUMN OWNER_USER_REF_ID VARCHAR(32) NULL COMMENT '所有者用户物理主键',
    MODIFY COLUMN ORG_ID VARCHAR(32) NULL COMMENT '旧机构业务号，兼容字段';

ALTER TABLE PEACH_FILE_UPLOAD_SESSION
    ADD COLUMN ID VARCHAR(32) NULL COMMENT 'UUID物理主键' FIRST,
    ADD COLUMN TENANT_REF_ID VARCHAR(32) NULL COMMENT '物理租户主键',
    ADD COLUMN APP_REF_ID VARCHAR(32) NULL COMMENT '物理应用主键',
    ADD COLUMN ORG_REF_ID VARCHAR(32) NULL COMMENT '物理机构主键',
    ADD COLUMN OWNER_USER_REF_ID VARCHAR(32) NULL COMMENT '所有者用户物理主键',
    ADD COLUMN MEMBER_REF_ID VARCHAR(32) NULL COMMENT '上传成员物理主键',
    MODIFY COLUMN ORG_ID VARCHAR(32) NULL COMMENT '旧机构业务号，兼容字段';

-- Give existing rows new physical IDs; never rewrite old permanent business IDs.
UPDATE PEACH_FILE_RECORD SET ID = REPLACE(UUID(), '-', '') WHERE ID IS NULL;
UPDATE PEACH_FILE_OBJECT SET ID = REPLACE(UUID(), '-', '') WHERE ID IS NULL;
UPDATE PEACH_FILE_UPLOAD_SESSION SET ID = REPLACE(UUID(), '-', '') WHERE ID IS NULL;

-- Stop on duplicate/NULL IDs or any mismatched legacy-object relation.
SELECT COUNT(*) AS missing_record_id FROM PEACH_FILE_RECORD WHERE ID IS NULL;
SELECT COUNT(*) AS missing_object_id FROM PEACH_FILE_OBJECT WHERE ID IS NULL;
SELECT COUNT(*) AS missing_session_id FROM PEACH_FILE_UPLOAD_SESSION WHERE ID IS NULL;
SELECT FILE_ID, COUNT(*) AS n FROM PEACH_FILE_RECORD GROUP BY FILE_ID HAVING COUNT(*) > 1;
SELECT OBJECT_ID, COUNT(*) AS n FROM PEACH_FILE_OBJECT GROUP BY OBJECT_ID HAVING COUNT(*) > 1;
SELECT SESSION_ID, COUNT(*) AS n FROM PEACH_FILE_UPLOAD_SESSION GROUP BY SESSION_ID HAVING COUNT(*) > 1;
SELECT R.FILE_ID
FROM PEACH_FILE_RECORD R
LEFT JOIN PEACH_FILE_OBJECT O ON O.OBJECT_ID = R.OBJECT_ID
WHERE R.OBJECT_ID IS NOT NULL AND O.OBJECT_ID IS NULL;

-- DBA must verify the above results before performing the primary-key cutover.
ALTER TABLE PEACH_FILE_RECORD
    MODIFY COLUMN ID VARCHAR(32) NOT NULL COMMENT 'UUID物理主键',
    DROP PRIMARY KEY,
    ADD PRIMARY KEY (ID),
    ADD UNIQUE KEY UK_FILE_RECORD_FILE_ID (FILE_ID),
    ADD INDEX IDX_FILE_RECORD_SAAS_SCOPE (TENANT_REF_ID, APP_REF_ID, OWNER_USER_REF_ID),
    ADD INDEX IDX_FILE_RECORD_SAAS_ORG (TENANT_REF_ID, APP_REF_ID, ORG_REF_ID, IS_DELETE, CREATED_TIME);
ALTER TABLE PEACH_FILE_OBJECT
    MODIFY COLUMN ID VARCHAR(32) NOT NULL COMMENT 'UUID物理主键',
    DROP PRIMARY KEY,
    ADD PRIMARY KEY (ID),
    ADD UNIQUE KEY UK_FILE_OBJECT_OBJECT_ID (OBJECT_ID),
    ADD INDEX IDX_FILE_OBJECT_SAAS_SCOPE (TENANT_REF_ID, APP_REF_ID, OWNER_USER_REF_ID),
    ADD INDEX IDX_FILE_OBJECT_SAAS_DEDUP (TENANT_REF_ID, APP_REF_ID, OWNER_USER_REF_ID, ORG_REF_ID, HASH_SHA256, FILE_SIZE);
ALTER TABLE PEACH_FILE_UPLOAD_SESSION
    MODIFY COLUMN ID VARCHAR(32) NOT NULL COMMENT 'UUID物理主键',
    DROP PRIMARY KEY,
    ADD PRIMARY KEY (ID),
    ADD UNIQUE KEY UK_FILE_UPLOAD_SESSION_SESSION_ID (SESSION_ID),
    ADD INDEX IDX_FILE_UPLOAD_SESSION_SAAS_SCOPE (TENANT_REF_ID, APP_REF_ID, OWNER_USER_REF_ID);

-- Mandatory manual reconciliation: only trusted historical evidence may populate
-- (TENANT_REF_ID, APP_REF_ID, OWNER_USER_REF_ID, ORG_REF_ID, MEMBER_REF_ID).
-- Cross-check that the linked object and record are in the SAME tenant and app.
SELECT COUNT(*) AS unmapped_records
FROM PEACH_FILE_RECORD
WHERE TENANT_REF_ID IS NULL OR APP_REF_ID IS NULL OR OWNER_USER_REF_ID IS NULL;
SELECT COUNT(*) AS unmapped_objects
FROM PEACH_FILE_OBJECT
WHERE TENANT_REF_ID IS NULL OR APP_REF_ID IS NULL OR OWNER_USER_REF_ID IS NULL;
SELECT COUNT(*) AS unmapped_sessions
FROM PEACH_FILE_UPLOAD_SESSION
WHERE TENANT_REF_ID IS NULL OR APP_REF_ID IS NULL
   OR OWNER_USER_REF_ID IS NULL OR MEMBER_REF_ID IS NULL;
SELECT R.FILE_ID
FROM PEACH_FILE_RECORD R JOIN PEACH_FILE_OBJECT O ON O.OBJECT_ID = R.OBJECT_ID
WHERE R.TENANT_REF_ID IS NOT NULL AND O.TENANT_REF_ID IS NOT NULL
  AND (R.TENANT_REF_ID <> O.TENANT_REF_ID OR R.APP_REF_ID <> O.APP_REF_ID);

