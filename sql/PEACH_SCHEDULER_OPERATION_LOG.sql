CREATE TABLE `PEACH_SCHEDULER_OPERATION_LOG` (
  `ID` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '操作日志主键',
  `OPERATION` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '操作编码，如 RUN、RETRY、CANCEL',
  `TARGET_TYPE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '目标类型：JOB、EXECUTION',
  `TARGET_ID` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '目标标识',
  `OPERATOR_ID` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '操作人 ID',
  `REASON` varchar(512) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '操作原因',
  `RESULT` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '操作结果：SUCCESS、FAILED',
  `CREATED_TIME` datetime(3) NOT NULL COMMENT '创建时间',
  PRIMARY KEY (`ID`),
  KEY `IDX_SCHEDULER_OPERATION_TARGET` (`TARGET_TYPE`,`TARGET_ID`,`CREATED_TIME`),
  KEY `IDX_SCHEDULER_OPERATION_OPERATOR` (`OPERATOR_ID`,`CREATED_TIME`),
  KEY `IDX_SCHEDULER_OPERATION_TIME` (`CREATED_TIME`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='调度人工操作审计表';
