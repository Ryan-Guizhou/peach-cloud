CREATE TABLE `MQ_CONSUME_RECORD` (
  `ID` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键 ID',
  `IDEMPOTENT_KEY` varchar(256) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '幂等键',
  `CONSUMER_GROUP` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '消费者组',
  `TOPIC` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'RocketMQ Topic',
  `TAG` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'RocketMQ Tag',
  `BUSINESS_KEY` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '业务 Key',
  `MESSAGE_ID` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '消息 ID',
  `STATUS` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '状态：PROCESSING、SUCCESS、FAILED',
  `OWNER_TOKEN` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '当前认领者令牌',
  `LEASE_UNTIL` datetime(3) DEFAULT NULL COMMENT '当前认领租约截止时间',
  `EXPIRES_AT` datetime(3) DEFAULT NULL COMMENT '成功幂等记录的保留截止时间',
  `CONSUME_COUNT` int(11) NOT NULL DEFAULT '0' COMMENT '消费次数',
  `LAST_ERROR` varchar(1000) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '脱敏后的最近错误',
  `CREATED_AT` datetime(3) NOT NULL COMMENT '创建时间',
  `UPDATED_AT` datetime(3) NOT NULL COMMENT '更新时间',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_MQ_CONSUME_IDEMPOTENT` (`IDEMPOTENT_KEY`,`CONSUMER_GROUP`),
  KEY `IDX_MQ_CONSUME_MESSAGE` (`MESSAGE_ID`),
  KEY `IDX_MQ_CONSUME_STATUS_UPDATE` (`STATUS`,`UPDATED_AT`),
  KEY `IDX_MQ_CONSUME_LEASE` (`STATUS`,`LEASE_UNTIL`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='RocketMQ JDBC 消费幂等记录表';
