CREATE TABLE PEACH_TENANT_MEMBER
(
    ID                 VARCHAR(32) NOT NULL COMMENT '物理主键',
    MEMBER_ID          VARCHAR(32) NOT NULL COMMENT '永久业务成员ID',
    TENANT_REF_ID      VARCHAR(32) NOT NULL COMMENT '关联租户物理ID',
    USER_REF_ID        VARCHAR(32) NOT NULL COMMENT '关联用户物理ID',
    STATUS             VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED LEFT',
    IS_DELETE          TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    CREATED_TIME       VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID         VARCHAR(32) NULL COMMENT '创建人ID',
    MODIFY_TIME        VARCHAR(20) NULL COMMENT '修改时间',
    MODIFIER_ID        VARCHAR(32) NULL COMMENT '修改人ID',
    DELETED_AT         DATETIME(3) NULL COMMENT '逻辑删除时间',
    DELETED_BY_REF_ID  VARCHAR(32) NULL COMMENT '逻辑删除操作者物理ID',
    VERSION            BIGINT NOT NULL DEFAULT 0 COMMENT '成员乐观锁版本',
    AUTH_VERSION       BIGINT NOT NULL DEFAULT 0 COMMENT '角色资源授权版本，仅递增',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_TENANT_MEMBER_BIZ (MEMBER_ID),
    UNIQUE KEY UK_MEMBER_USER_TENANT (TENANT_REF_ID, USER_REF_ID),
    KEY IDX_MEMBER_USER_ACTIVE (USER_REF_ID, STATUS, IS_DELETE),
    KEY IDX_MEMBER_TENANT_ACTIVE (TENANT_REF_ID, STATUS, IS_DELETE),
    CONSTRAINT CK_MEMBER_AUTH_VERSION CHECK (AUTH_VERSION >= 0)
) COMMENT='租户成员关系表';
