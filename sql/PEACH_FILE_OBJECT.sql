CREATE TABLE `PEACH_FILE_OBJECT` (
  `OBJECT_ID` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '物理对象ID',
  `HASH_SHA256` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'SHA-256摘要',
  `HASH_MD5` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'MD5摘要',
  `FILE_SIZE` bigint(20) DEFAULT NULL COMMENT '文件大小',
  `STORAGE_PROVIDER` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '存储提供方',
  `BUCKET_NAME` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'bucket名称',
  `OBJECT_KEY` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '对象key',
  `ORIGIN_FILE_NAME` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '原始文件名',
  `CONTENT_TYPE` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '内容类型',
  `EXTENSION` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '扩展名',
  `STORAGE_STATUS` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '存储状态',
  `REF_COUNT` int(11) DEFAULT NULL COMMENT '引用数量',
  `UPLOAD_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '上传完成时间',
  `LAST_ACCESS_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '最后访问时间',
  `TENANT_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '租户ID',
  `ORG_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '机构ID',
  `IS_DELETE` tinyint(1) DEFAULT '0' COMMENT '逻辑删除标记',
  `CREATED_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建时间',
  `CREATOR_ID` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建人ID',
  `MODIFY_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改时间',
  `MODIFIER_ID` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改人ID',
  PRIMARY KEY (`OBJECT_ID`),
  KEY `IDX_FILE_OBJECT_CONTEXT_STATUS` (`TENANT_ID`,`ORG_ID`,`STORAGE_STATUS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='文件物理对象表';
