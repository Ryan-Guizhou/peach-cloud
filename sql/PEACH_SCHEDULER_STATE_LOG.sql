CREATE TABLE `PEACH_SCHEDULER_STATE_LOG` (
  `ID` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '状态日志主键',
  `AGGREGATE_TYPE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '聚合类型：JOB、EXECUTION',
  `AGGREGATE_ID` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '聚合标识',
  `FROM_STATE` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '迁移前状态',
  `EVENT` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '状态事件',
  `TO_STATE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '迁移后状态',
  `OPERATOR_ID` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '操作人 ID',
  `REMARK` varchar(512) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '备注',
  `CREATED_TIME` datetime(3) NOT NULL COMMENT '创建时间',
  PRIMARY KEY (`ID`),
  KEY `IDX_SCHEDULER_STATE_LOG_AGGREGATE` (`AGGREGATE_TYPE`,`AGGREGATE_ID`,`CREATED_TIME`),
  KEY `IDX_SCHEDULER_STATE_LOG_TIME` (`CREATED_TIME`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='调度状态迁移审计表';
