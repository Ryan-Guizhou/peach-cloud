CREATE TABLE `PEACH_USER_AVATAR_HISTORY` (
  `AVATAR_HISTORY_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '头像历史ID',
  `USER_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '用户ID',
  `FILE_ID` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '文件服务业务文件ID',
  `SORT_NO` int(11) NOT NULL COMMENT '排序号，1为最近使用',
  `IS_CURRENT` tinyint(1) DEFAULT '0' COMMENT '是否当前头像',
  `IS_DELETE` tinyint(1) DEFAULT '0' COMMENT '逻辑删除',
  `CREATED_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建时间',
  `CREATOR_ID` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建人ID',
  `MODIFY_TIME` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改时间',
  `MODIFIER_ID` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '修改人ID',
  PRIMARY KEY (`AVATAR_HISTORY_ID`),
  UNIQUE KEY `UK_USER_AVATAR_FILE` (`USER_ID`,`FILE_ID`),
  KEY `IDX_USER_AVATAR_ORDER` (`USER_ID`,`IS_DELETE`,`SORT_NO`),
  KEY `IDX_USER_AVATAR_CURRENT` (`USER_ID`,`IS_CURRENT`,`IS_DELETE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户头像历史表';
