CREATE TABLE PEACH_USER
(
    USER_ID             VARCHAR(32) NOT NULL COMMENT '用户ID',
    USER_CODE           VARCHAR(32) NULL COMMENT '用户账号',
    PASSWORD            VARCHAR(32) NULL COMMENT '用户密码',
    USER_NAME           VARCHAR(50) NULL COMMENT '用户名称',
    IDENTITY_CODE       VARCHAR(30) NULL COMMENT '用户身份证号',
    INVLIDATE           VARCHAR(20) NULL COMMENT '密码失效日期',
    AUTH_MODE           VARCHAR(20) NULL COMMENT '认证方式',
    STATUS              VARCHAR(20) NULL COMMENT '状态',
    UNLOCK_TIME         VARCHAR(20) NULL COMMENT '解锁时间',
    MENU_STYLE          VARCHAR(20) NULL COMMENT '菜单风格',
    MENU_ROLE           VARCHAR(128) NULL COMMENT '菜单角色',
    LASTEST_LOGIN       VARCHAR(20) NULL COMMENT '最近登录时间',
    ERROR_COUNT         VARCHAR(20) NULL COMMENT '密码错误次数',
    START_DATE          VARCHAR(20) NULL COMMENT '有效期开始',
    END_DATE            VARCHAR(20) NULL COMMENT '有效期结束',
    MOBILE_PHONE        VARCHAR(11) NULL COMMENT '手机号',
    EMAIL               VARCHAR(32) NULL COMMENT '邮箱',
    CREATE_USER         VARCHAR(32) NULL COMMENT '创建人',
    CREATE_TIME         VARCHAR(20) NULL COMMENT '创建时间',
    LAST_MODIFY_TIME    MEDIUMTEXT  NULL COMMENT '最新修改时间',
    IS_DELETE           TINYINT(1) DEFAULT 0 COMMENT '是否删除',
    IS_MODIFY           TINYINT(1) DEFAULT 0 COMMENT '密码是否修改',
    PASSWD_MODIFY_TIME  VARCHAR(20) NULL COMMENT '密码修改时间',
    PRIMARY KEY (USER_ID),
    UNIQUE KEY IDX_USER_CODE (USER_CODE)
) COMMENT='用户信息表';
