CREATE TABLE `PEACH_SCHEDULER_HANDLER` (
  `ID` bigint(20) NOT NULL AUTO_INCREMENT COMMENT 'Handler 主键',
  `APPLICATION_NAME` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '业务应用名称',
  `HANDLER_NAME` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'Handler 名称',
  `DESCRIPTION` varchar(512) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Handler 说明',
  `STATUS` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '状态：ONLINE、OFFLINE',
  `INSTANCE_ID` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '最近上报实例标识',
  `LAST_HEARTBEAT_TIME` datetime(3) NOT NULL COMMENT '最近心跳时间',
  `CREATED_TIME` datetime(3) NOT NULL COMMENT '创建时间',
  `MODIFY_TIME` datetime(3) NOT NULL COMMENT '修改时间',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_SCHEDULER_HANDLER` (`APPLICATION_NAME`,`HANDLER_NAME`),
  KEY `IDX_SCHEDULER_HANDLER_STATUS` (`STATUS`,`LAST_HEARTBEAT_TIME`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='调度 Handler 注册白名单表';
