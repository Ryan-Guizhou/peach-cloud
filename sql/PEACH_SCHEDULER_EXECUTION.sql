CREATE TABLE PEACH_SCHEDULER_EXECUTION
(
    EXECUTION_ID      VARCHAR(64)  NOT NULL COMMENT '执行实例 ID',
    JOB_ID            BIGINT       NOT NULL COMMENT '任务主键',
    JOB_CODE          VARCHAR(128) NOT NULL COMMENT '稳定任务编码',
    OCCURRENCE_KEY    VARCHAR(192) NOT NULL COMMENT '逻辑 occurrence 幂等键',
    TRIGGER_TYPE      VARCHAR(32)  NOT NULL COMMENT '触发类型：SCHEDULED、MANUAL',
    SCHEDULED_TIME    DATETIME(3)  NOT NULL COMMENT '计划执行时间',
    STATE             VARCHAR(32)  NOT NULL COMMENT '执行生命周期状态',
    ATTEMPT           INT          NOT NULL DEFAULT 1 COMMENT '当前尝试次数',
    EXECUTOR_INSTANCE VARCHAR(128) NULL COMMENT '当前执行器实例标识',
    LEASE_UNTIL       DATETIME(3)  NULL COMMENT '执行租约过期时间',
    NEXT_RETRY_TIME   DATETIME(3)  NULL COMMENT '下次允许重试时间',
    START_TIME        DATETIME(3)  NULL COMMENT '实际开始时间',
    FINISH_TIME       DATETIME(3)  NULL COMMENT '实际结束时间',
    DURATION_MS       BIGINT       NULL COMMENT '执行耗时毫秒数',
    TRACE_ID          VARCHAR(128) NULL COMMENT '链路追踪 ID',
    ERROR_TYPE        VARCHAR(128) NULL COMMENT '失败类型',
    ERROR_MESSAGE     VARCHAR(1000) NULL COMMENT '脱敏后的失败摘要',
    VERSION           BIGINT       NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
    CREATED_TIME      DATETIME(3)  NOT NULL COMMENT '创建时间',
    MODIFY_TIME       DATETIME(3)  NOT NULL COMMENT '修改时间',
    PRIMARY KEY (EXECUTION_ID),
    UNIQUE KEY UK_SCHEDULER_EXECUTION_OCCURRENCE (OCCURRENCE_KEY),
    KEY IDX_SCHEDULER_EXECUTION_JOB_TIME (JOB_ID, CREATED_TIME),
    KEY IDX_SCHEDULER_EXECUTION_STATE_TIME (STATE, CREATED_TIME),
    KEY IDX_SCHEDULER_EXECUTION_LEASE (STATE, LEASE_UNTIL),
    KEY IDX_SCHEDULER_EXECUTION_RETRY (STATE, NEXT_RETRY_TIME),
    KEY IDX_SCHEDULER_EXECUTION_JOB_CODE (JOB_CODE)
) COMMENT='调度逻辑执行 occurrence 表';
