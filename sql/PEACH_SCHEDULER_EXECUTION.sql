CREATE TABLE `PEACH_SCHEDULER_EXECUTION` (
  `EXECUTION_ID` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '执行实例 ID',
  `JOB_ID` bigint(20) NOT NULL COMMENT '任务主键',
  `JOB_CODE` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '稳定任务编码',
  `OCCURRENCE_KEY` varchar(192) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '逻辑 occurrence 幂等键',
  `TRIGGER_TYPE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '触发类型：SCHEDULED、MANUAL',
  `SCHEDULED_TIME` datetime(3) NOT NULL COMMENT '计划执行时间',
  `STATE` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '执行生命周期状态',
  `ATTEMPT` int(11) NOT NULL DEFAULT '1' COMMENT '当前尝试次数',
  `EXECUTOR_INSTANCE` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '当前执行器实例标识',
  `LEASE_UNTIL` datetime(3) DEFAULT NULL COMMENT '执行租约过期时间',
  `NEXT_RETRY_TIME` datetime(3) DEFAULT NULL COMMENT '下次允许重试时间',
  `START_TIME` datetime(3) DEFAULT NULL COMMENT '实际开始时间',
  `FINISH_TIME` datetime(3) DEFAULT NULL COMMENT '实际结束时间',
  `DURATION_MS` bigint(20) DEFAULT NULL COMMENT '执行耗时毫秒数',
  `TRACE_ID` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '链路追踪 ID',
  `ERROR_TYPE` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '失败类型',
  `ERROR_MESSAGE` varchar(1000) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '脱敏后的失败摘要',
  `VERSION` bigint(20) NOT NULL DEFAULT '0' COMMENT '乐观锁版本号',
  `CREATED_TIME` datetime(3) NOT NULL COMMENT '创建时间',
  `MODIFY_TIME` datetime(3) NOT NULL COMMENT '修改时间',
  PRIMARY KEY (`EXECUTION_ID`),
  UNIQUE KEY `UK_SCHEDULER_EXECUTION_OCCURRENCE` (`OCCURRENCE_KEY`),
  KEY `IDX_SCHEDULER_EXECUTION_JOB_TIME` (`JOB_ID`,`CREATED_TIME`),
  KEY `IDX_SCHEDULER_EXECUTION_STATE_TIME` (`STATE`,`CREATED_TIME`),
  KEY `IDX_SCHEDULER_EXECUTION_LEASE` (`STATE`,`LEASE_UNTIL`),
  KEY `IDX_SCHEDULER_EXECUTION_RETRY` (`STATE`,`NEXT_RETRY_TIME`),
  KEY `IDX_SCHEDULER_EXECUTION_JOB_CODE` (`JOB_CODE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='调度逻辑执行 occurrence 表';
