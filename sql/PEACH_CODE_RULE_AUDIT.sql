CREATE TABLE PEACH_CODE_RULE_AUDIT
(
    ID                 VARCHAR(32) NOT NULL COMMENT '变更日志物理主键',
    RULE_REF_ID        VARCHAR(32) NOT NULL COMMENT '规则物理主键',
    RULE_VERSION       BIGINT NOT NULL COMMENT '变更后的规则版本',
    OPERATOR_REF_ID    VARCHAR(32) NOT NULL COMMENT '操作人物理主键',
    OPERATION          VARCHAR(16) NOT NULL COMMENT 'STATUS FORMAT WATERMARK',
    OLD_STATUS         VARCHAR(16) NOT NULL COMMENT '变更前状态',
    NEW_STATUS         VARCHAR(16) NOT NULL COMMENT '变更后状态',
    OLD_SEPARATOR      VARCHAR(1) NOT NULL COMMENT '变更前分隔符',
    NEW_SEPARATOR      VARCHAR(1) NOT NULL COMMENT '变更后分隔符',
    OLD_WIDTH          INT NOT NULL COMMENT '变更前数字宽度',
    NEW_WIDTH          INT NOT NULL COMMENT '变更后数字宽度',
    OLD_WATERMARK      BIGINT NOT NULL COMMENT '变更前永久水位',
    NEW_WATERMARK      BIGINT NOT NULL COMMENT '变更后永久水位',
    CREATED_AT         DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '变更时间',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_CODE_RULE_AUDIT_VERSION (RULE_REF_ID, RULE_VERSION),
    KEY IDX_CODE_RULE_AUDIT_CREATED (CREATED_AT)
) COMMENT='业务编码规则受控变更不可复用历史';
