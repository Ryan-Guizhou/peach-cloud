CREATE TABLE PEACH_ROLE_DATA_POLICY
(
    ID                  VARCHAR(32) NOT NULL COMMENT 'UUID物理主键',
    TENANT_REF_ID       VARCHAR(32) NOT NULL COMMENT '物理租户ID',
    APP_REF_ID          VARCHAR(32) NOT NULL COMMENT '物理应用ID',
    ROLE_REF_ID         VARCHAR(32) NOT NULL COMMENT '物理角色ID',
    PERMISSION_REF_ID   VARCHAR(32) NOT NULL COMMENT '同角色动作权限物理ID',
    DATA_SCOPE          VARCHAR(16) NOT NULL COMMENT 'SELF ORG ORG_TREE TENANT_ALL',
    ORG_REF_ID          VARCHAR(32) NULL COMMENT 'ORG/ORG_TREE生效的机构物理ID',
    ORG_SCOPE_KEY       VARCHAR(32) GENERATED ALWAYS AS (COALESCE(ORG_REF_ID, 'NO_ORG')) STORED,
    STATUS              VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE DISABLED',
    IS_DELETE           TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    VERSION             BIGINT NOT NULL DEFAULT 0 COMMENT '乐观版本',
    ACTIVE_SLOT         TINYINT GENERATED ALWAYS AS (CASE WHEN IS_DELETE = 0 THEN 1 ELSE NULL END) STORED,
    CREATED_TIME        VARCHAR(20) NULL COMMENT '创建时间',
    CREATOR_ID          VARCHAR(32) NULL COMMENT '创建人成员物理ID',
    DELETED_AT          DATETIME(3) NULL COMMENT '删除时间',
    PRIMARY KEY (ID),
    UNIQUE KEY UK_ROLE_DATA_POLICY_ACTIVE (TENANT_REF_ID, ROLE_REF_ID, PERMISSION_REF_ID, DATA_SCOPE, ORG_SCOPE_KEY, ACTIVE_SLOT),
    KEY IDX_ROLE_DATA_POLICY_ACTION (TENANT_REF_ID, APP_REF_ID, ROLE_REF_ID, PERMISSION_REF_ID, STATUS, IS_DELETE),
    CONSTRAINT CK_ROLE_DATA_SCOPE CHECK (DATA_SCOPE IN ('SELF', 'ORG', 'ORG_TREE', 'TENANT_ALL')),
    CONSTRAINT CK_ROLE_DATA_SCOPE_ANCHOR CHECK ((DATA_SCOPE IN ('SELF','TENANT_ALL') AND ORG_REF_ID IS NULL)
        OR (DATA_SCOPE IN ('ORG','ORG_TREE') AND ORG_REF_ID IS NOT NULL)),
    CONSTRAINT CK_ROLE_DATA_POLICY_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED'))
) COMMENT='每个角色动作权限的独立行范围策略，与成员角色绑定范围求交';
