import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, '../..');

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 1) {
    const key = argv[i];
    if (!key.startsWith('--')) continue;
    args[key.slice(2)] = argv[i + 1];
    i += 1;
  }
  return args;
}

function parseEnv(text) {
  const result = new Map();
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const index = line.indexOf('=');
    if (index <= 0) continue;
    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    result.set(key, value);
  }
  return result;
}

function quote(value) {
  const escaped = String(value)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\$/g, '\\$')
    .replace(/`/g, '\\`');
  return `"${escaped}"`;
}

function requireValue(values, key) {
  const value = values.get(key);
  if (!value || /^change_me/i.test(value)) throw new Error(`Missing required private value: ${key}`);
}

const args = parseArgs(process.argv.slice(2));
const secretsPath = path.resolve(args.secrets ?? process.env.PEACH_SECRET_FILE ?? path.join(root, 'env/deploy.env'));
const outputPath = path.resolve(args.output ?? path.join(root, 'runtime/generated/deploy.env'));
const defaultsPath = path.join(root, 'env/defaults.env');

if (!fs.existsSync(defaultsPath)) throw new Error(`Missing defaults file: ${defaultsPath}`);
if (!fs.existsSync(secretsPath)) throw new Error(`Missing private deployment file: ${secretsPath}`);

const defaults = parseEnv(fs.readFileSync(defaultsPath, 'utf8'));
const secrets = parseEnv(fs.readFileSync(secretsPath, 'utf8'));
const values = new Map(defaults);
for (const [key, value] of secrets) values.set(key, value);

for (const key of ['PEACH_RUNTIME_ROOT','PEACH_LOG_ROOT','MYSQL_ROOT_PASSWORD','REDIS_PASSWORD','MONGO_ROOT_PASSWORD','MONGO_APP_PASSWORD','MAVEN_NEXUS_USERNAME','MAVEN_NEXUS_PASSWORD','GRAFANA_ADMIN_PASSWORD']) requireValue(values, key);

if (!values.get('PEACH_MONGO_URI')) {
  const user = encodeURIComponent(values.get('MONGO_APP_USERNAME') || 'peach');
  const password = encodeURIComponent(values.get('MONGO_APP_PASSWORD'));
  const database = values.get('MONGO_DATABASE') || 'peach_cloud';
  values.set('PEACH_MONGO_URI', `mongodb://${user}:${password}@mongodb:27017/${database}?authSource=${encodeURIComponent(database)}`);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
const header = '# Generated by scripts/config/render-runtime-env.mjs. Do not edit or commit.\n';
const body = [...values.entries()].map(([key, value]) => `${key}=${quote(value)}`).join('\n');
fs.writeFileSync(outputPath, `${header}${body}\n`, { encoding: 'utf8', mode: 0o600 });
fs.chmodSync(outputPath, 0o600);
console.log(outputPath);
